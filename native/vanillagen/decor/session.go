// Decoration messages (see protocol.go in package main for the framing):
//
//	client -> server  INIT    0x10  i32 minY, i32 height, i32 seaLevel, u16 n, str[n] registry biome names (registry
//	                                order), u16 m, (u16 bedrock id, u16 k, u16[k] registry biome indexes)[m],
//	                                u16 t, u16[t] registry biome index of every terrain biome (by the READY names),
//	                                u8 steps, (u16 c, str[c] placed feature ids)[steps] (global feature order),
//	                                u32 empty (PHP's empty block id, air), u32 water (PocketMine water state)
//	server -> client  READY   0x90  u8 steps, (u16 c, u8[ceil(c / 8)] natively placed bitmap)[steps],
//	                                u16 e, (str id, str reason)[e] (features left to PHP and why, for the logs)
//	client -> server  BEGIN   0x11  i32 chunkX, i32 chunkZ, 9 chunks ((dx + 1) * 3 + dz + 1): u8 has terrain heights,
//	                                [heights], sections: block layer, liquid layer, biome array (see readSection)
//	client -> server  PLACE   0x12  i64 decoration seed, u8 has gaussian, f64 gaussian, u32 w, (u32 key, u32 state,
//	                                u32 block)[w] PHP writes since the last sync (key bit 31: written by setPmState, no
//	                                heightmap update; block: the PocketMine state written, bit 31 = water in the liquid
//	                                layer), u8 h, (u8 chunk index, heights)[h] terrain heights PHP computed since,
//	                                u16 f, (u8 step, u16 index)[f] features to place in order
//	server -> client  NEED_RT 0x94  u16 n, u16[n] states: PHP's block of fromPm(toPm(state)) is needed (terrain
//	                                heights rebuild of a chunk generated by another worker, see Region)
//	client -> server  RT      0x14  u16[n] block indexes
//	server -> client  NEED_PM 0x95  u16 n, u16[n] states: the PocketMine state of each is needed (PHP's toPm() and
//	                                pmNeedsWater(), cached by the session)
//	client -> server  PM      0x15  (u32 PocketMine state, u8 needs water)[n]
//	server -> client  DONE    0x92  native writes (see appendWrites and appendLayers), u8 has gaussian, f64 gaussian,
//	                                u8 h, (u8 chunk index, heights)[h] terrain heights computed natively
//	server -> client  FAIL    0x93  str message: the decoration request failed (the session stays usable for
//	                                terrain; the client goes on with PHP)
//
// heights: u16[512] WORLD_SURFACE_WG then OCEAN_FLOOR_WG minus minY, index x | z << 4.
const (
	MsgInit   = 0x10
	MsgBegin  = 0x11
	MsgPlace  = 0x12
	MsgRt     = 0x14
	MsgPm     = 0x15
	MsgNeedPm = 0x95
	MsgReady  = 0x90
	MsgNeedRt = 0x94
	MsgDone   = 0x92
	MsgFail   = 0x93

	keyNoHeightmap = 1 << 31
)

// Transport sends one frame and receives the next one (for the NEED_RT callback).
type Transport struct {
	Send    func(payload []byte) error
	Receive func() ([]byte, error)
}

// Session is the decoration state of one connection (one PHP generator).
type Session struct {
	b        *Blocks
	reg      *Registry
	region   *Region
	biomes   *Biomes
	random   *Random
	ctx      *Ctx
	minY     int
	height   int
	sections int

	rtBlock      []int32
	stepFeatures [][]string
	placed       [][]*PlacedFeature // nil: left to PHP

	pm        *pmLayers
	pmState   []int64 // PocketMine state | water << 32 per Java state, -1 if not known yet
	pmQueue   []int
	blockIdx  [4096]uint16
	liquidIdx [4096]uint16
	dry, wet  []uint16

	begun   bool
	failure error
	out     []byte
}

// NewSession handles INIT. sampleTerrainBiome returns the terrain biome (index into the generator's tree names) of
// a cell.
func NewSession(data *worldgen.Data, seed int64, payload []byte, sampleTerrainBiome func(qx, qy, qz int) int) (*Session, []byte, error) {
	if err := LibmCheck(); err != nil {
		return nil, nil, err
	}
	r := &rd{b: payload}
	minY := int(r.i32())
	height := int(r.i32())
	seaLevel := int(r.i32())
	n := int(r.u16())
	names := make([]string, n)
	for i := range names {
		names[i] = r.str()
	}
	bedrockToJava := map[int][]int{}
	m := int(r.u16())
	for i := 0; i < m; i++ {
		id := int(r.u16())
		k := int(r.u16())
		list := make([]int, k)
		for j := range list {
			list[j] = int(r.u16())
		}
		bedrockToJava[id] = list
	}
	t := int(r.u16())
	terrainToRegistry := make([]int, t)
	for i := range terrainToRegistry {
		terrainToRegistry[i] = int(r.u16())
	}
	steps := int(r.u8())
	stepFeatures := make([][]string, steps)
	for s := range stepFeatures {
		c := int(r.u16())
		stepFeatures[s] = make([]string, c)
		for i := range stepFeatures[s] {
			stepFeatures[s][i] = r.str()
		}
	}
	pmEmpty := r.u32()
	pmWater := r.u32()
	if r.err != nil || len(r.b) != 0 {
		return nil, nil, errors.New("malformed decoration INIT")
	}
	if height <= 0 || height%16 != 0 || minY%16 != 0 {
		return nil, nil, errors.New("invalid decoration height")
	}
	b, err := LoadBlocks(data.Root())
	if err != nil {
		return nil, nil, err
	}
	reg, err := NewRegistry(data, b, names)
	if err != nil {
		return nil, nil, err
	}
	sample := func(qx, qy, qz int) int {
		tb := sampleTerrainBiome(qx, qy, qz)
		if tb < 0 || tb >= len(terrainToRegistry) {
			panic(sessionError{fmt.Errorf("terrain biome %d has no registry biome", tb)})
		}
		return terrainToRegistry[tb]
	}
	biomes := NewBiomes(worldgen.ObfuscateSeed(seed), minY, height, bedrockToJava, sample)
	region := NewRegion(b, minY, height, seaLevel, seed, biomes)
	rtBlock := make([]int32, len(b.BlockOf))
	for i := range rtBlock {
		rtBlock[i] = -1
	}
	region.RtBlock = rtBlock
	random := &Random{}
	pm := newPmLayers(height >> 4)
	pm.empty, pm.water = pmEmpty, pmWater
	pmState := make([]int64, len(b.BlockOf))
	for i := range pmState {
		pmState[i] = -1
	}
	s := &Session{
		pm: pm, pmState: pmState,
		b: b, reg: reg, region: region, biomes: biomes, random: random, minY: minY, height: height, sections: height >> 4,
		stepFeatures: stepFeatures,
		rtBlock:      rtBlock,
		ctx:          &Ctx{Level: region, R: random, B: b, Reg: reg, Surv: SurvivalOf(b), MinGenY: minY, GenDepth: height, SeaLevel: seaLevel, Seed: seed},
	}
	region.Decode = s.decodeSection
	w := &wr{}
	w.u8(MsgReady)
	w.u8(byte(steps))
	var reasons []string
	s.placed = make([][]*PlacedFeature, steps)
	for st, ids := range stepFeatures {
		s.placed[st] = make([]*PlacedFeature, len(ids))
		bitmap := make([]byte, (len(ids)+7)/8)
		for i, id := range ids {
			p, err := reg.Placed(id)
			if err != nil {
				reasons = append(reasons, id, err.Error())
				continue
			}
			s.placed[st][i] = p
			bitmap[i>>3] |= 1 << (i & 7)
		}
		w.u16(uint16(len(ids)))
		w.b = append(w.b, bitmap...)
	}
	w.u16(uint16(len(reasons) / 2))
	for _, v := range reasons {
		w.str(v)
	}
	return s, w.b, nil
}

// Handle processes a decoration message. A returned error ends the connection; failures of a request are reported
// to the client with FAIL instead.
func (s *Session) Handle(msg byte, payload []byte, t Transport) error {
	switch msg {
	case MsgBegin:
		if err := s.begin(payload); err != nil {
			s.begun = false
			// BEGIN has no reply: the failure is reported on the next PLACE
			s.failure = err
		}
		return nil
	case MsgPlace:
		if s.failure != nil || !s.begun {
			err := s.failure
			if err == nil {
				err = errors.New("PLACE without BEGIN")
			}
			s.failure = nil
			return t.Send(failFrame(err))
		}
		done, err := s.place(payload, t)
		if err != nil {
			var transport transportError
			if errors.As(err, &transport) {
				return transport.err
			}
			s.begun = false
			return t.Send(failFrame(err))
		}
		return t.Send(done)
	}
	return fmt.Errorf("unexpected decoration message 0x%02x", msg)
}

func failFrame(err error) []byte {
	w := &wr{}
	w.u8(MsgFail)
	w.str(err.Error())
	return w.b
}

type transportError struct{ err error }

func (e transportError) Error() string { return e.err.Error() }

func (s *Session) begin(payload []byte) error {
	r := &rd{b: payload}
	cx := int(r.i32())
	cz := int(r.i32())
	region := s.region
	region.Begin(cx, cz)
	s.biomes.Begin(cx, cz)
	s.pm.begin()
	quartsY := s.height >> 2
	n := len(s.b.BlockOf)
	for ci := 0; ci < 9; ci++ {
		if r.u8() != 0 {
			h := &[2][256]int32{}
			for k := 0; k < 2; k++ {
				for i := 0; i < 256; i++ {
					h[k][i] = int32(r.u16()) + int32(s.minY)
				}
			}
			region.SetTerrainHeights(ci, h)
		}
		stored := s.biomes.Stored(ci)
		for sec := 0; sec < s.sections; sec++ {
			si := ci*s.sections + sec
			nonEmpty, err := s.readSection(r, &s.pm.src[si], n)
			if err != nil {
				return err
			}
			region.SetSectionNonEmpty(ci, sec, nonEmpty)
			// the states are decoded when the section is first used (most never are): decodeSection()
			region.SetSectionPending(si)
			// biome array: only the 64 cells are read
			bits, words, raw, p, err := readLayer(r, 2)
			if err != nil {
				return err
			}
			for qx := 0; qx < 4; qx++ {
				for qz := 0; qz < 4; qz++ {
					for qy := 0; qy < 4; qy++ {
						idx := (qx << 10) | (qz << 6) | (qy << 2) //(x << 8) | (z << 4) | y with x, z, y = q * 4
						o := paletteIndex(bits, words, idx)
						if o >= p {
							return errors.New("paletted array index out of range")
						}
						stored[((qx<<2)|qz)*quartsY+(sec<<2)+qy] = int16(binary.LittleEndian.Uint16(raw[o*2:]))
					}
				}
			}
		}
	}
	if r.err != nil || len(r.b) != 0 {
		return errors.New("malformed decoration BEGIN")
	}
	s.begun = true
	return nil
}

// readSection reads one section of a chunk (kept in src, decoded by decodeSection()):
//
//	u8 block bits (0xff: no block layer, the section is empty air), [u32 n, u8[n] words], u16 p,
//	(u32 block, u16 dry, u16 wet)[p]
//	u8 liquid bits (0xff: no liquid layer), [u32 n, u8[n] words], u16 q, u32[q] liquid layer states
//
// block is the PocketMine state, dry PHP's fromPm() of it; wet the same state with waterlogged=true (as
// FeatureLevel::getState() does when the liquid layer has water), or dry if the block cannot be waterlogged. The
// layers as they are also make the PocketMine layer replica (pmlayers.go). Returns whether the section has a block
// layer (SubChunk::isEmptyFast() negated).
func (s *Session) readSection(r *rd, src *pmSource, stateCount int) (bool, error) {
	src.blockBits, src.liqBits = 0xff, 0xff
	if r.peek() == 0xff {
		r.u8()
		// the liquid layer marker still follows
		if r.u8() != 0xff {
			return false, errors.New("liquid layer without block layer")
		}
		return false, nil
	}
	bits, words, raw, p, err := readLayer(r, 8)
	if err != nil {
		return false, err
	}
	for k := 0; k < p; k++ {
		if int(binary.LittleEndian.Uint16(raw[k*8+4:])) >= stateCount || int(binary.LittleEndian.Uint16(raw[k*8+6:])) >= stateCount {
			return false, errors.New("invalid Java state in palette")
		}
	}
	src.blockBits, src.blockWords, src.blockPal = bits, words, raw
	if r.peek() == 0xff {
		r.u8()
	} else {
		if bits, words, raw, _, err = readLayer(r, 4); err != nil {
			return false, err
		}
		src.liqBits, src.liqWords, src.liqPal = bits, words, raw
	}
	return true, nil
}

// decodeSection fills the Java states of a section from what BEGIN sent (Region.decode).
func (s *Session) decodeSection(si int, states []uint16) {
	src := &s.pm.src[si]
	if src.blockBits == 0xff {
		// no block layers: every block is PHP's empty block id (air), which maps to Java air
		air := uint16(s.b.Air)
		for i := range states {
			states[i] = air
		}
		return
	}
	p := len(src.blockPal) / 8
	if err := decodeOffsets(src.blockBits, src.blockWords, p, &s.blockIdx); err != nil {
		panic(sessionError{err})
	}
	dry := s.dry[:0]
	wet := s.wet[:0]
	for k := 0; k < p; k++ {
		dry = append(dry, binary.LittleEndian.Uint16(src.blockPal[k*8+4:]))
		wet = append(wet, binary.LittleEndian.Uint16(src.blockPal[k*8+6:]))
	}
	s.dry, s.wet = dry, wet
	idx := &s.blockIdx
	if src.liqBits == 0xff {
		for i := range states {
			states[i] = dry[idx[i]]
		}
		return
	}
	q := len(src.liqPal) / 4
	if err := decodeOffsets(src.liqBits, src.liqWords, q, &s.liquidIdx); err != nil {
		panic(sessionError{err})
	}
	var water [4096]bool
	isWater := water[:q]
	for k := range isWater {
		isWater[k] = binary.LittleEndian.Uint32(src.liqPal[k*4:]) == s.pm.water
	}
	lidx := &s.liquidIdx
	for i := range states {
		o := idx[i]
		state := dry[o]
		if wet[o] != state && isWater[lidx[i]] {
			state = wet[o]
		}
		states[i] = state
	}
}

// readLayer reads u8 bits, [u32 n, u8[n] words] (when bits > 0), u16 p, entry[p] (entrySize bytes each) and
// returns the bits, the words, the palette bytes and p, after checking the sizes.
func readLayer(r *rd, entrySize int) (uint8, []byte, []byte, int, error) {
	bits := r.u8()
	var words []byte
	if bits > 0 {
		words = r.take(int(r.u32()))
	}
	p := int(r.u16())
	if r.err != nil || p == 0 || p > 4096 {
		return 0, nil, nil, 0, errors.New("malformed paletted array")
	}
	raw := r.take(p * entrySize)
	if r.err != nil {
		return 0, nil, nil, 0, r.err
	}
	if bits > 16 || (bits > 0 && len(words) != pmWordCount(bits)*4) {
		return 0, nil, nil, 0, errors.New("malformed paletted array words")
	}
	return bits, words, raw, p, nil
}

// decodeOffsets decodes the palette offset of every block (index (x << 8) | (z << 4) | y) of a word array.
func decodeOffsets(bits uint8, words []byte, p int, out *[4096]uint16) error {
	if bits == 0 {
		clear(out[:])
		return nil
	}
	perWord := 32 / int(bits)
	mask := uint32(1)<<bits - 1
	idx := 0
	for w := 0; idx < 4096; w++ {
		word := binary.LittleEndian.Uint32(words[w*4:])
		for k := 0; k < perWord && idx < 4096; k++ {
			v := word & mask
			if int(v) >= p {
				return errors.New("paletted array index out of range")
			}
			out[idx] = uint16(v)
			word >>= bits
			idx++
		}
	}
	return nil
}

// paletteIndex is the palette offset of a block in a PalettedBlockArray word array (chunkutils2 layout).
func paletteIndex(bits uint8, words []byte, idx int) int {
	if bits == 0 {
		return 0
	}
	perWord := 32 / int(bits)
	w := idx / perWord
	shift := uint((idx % perWord) * int(bits))
	return int((binary.LittleEndian.Uint32(words[w*4:]) >> shift) & (1<<bits - 1))
}

func (s *Session) place(payload []byte, t Transport) (out []byte, err error) {
	r := &rd{b: payload}
	decorationSeed := int64(r.u64())
	haveGaussian := r.u8() != 0
	gaussian := math.Float64frombits(r.u64())
	region := s.region
	nw := int(r.u32())
	maxKey := RegionSize * RegionSize * s.height
	for i := 0; i < nw && r.err == nil; i++ {
		key := r.u32()
		state := int(r.u32())
		block := r.u32()
		k := int(key &^ keyNoHeightmap)
		if k >= maxKey || state >= len(s.b.BlockOf) {
			return nil, errors.New("invalid PHP write")
		}
		region.ApplyRemote(k, state, key&keyNoHeightmap == 0)
		sec, idx := s.pmPosition(k)
		if err := s.pm.write(sec, idx, block&^(1<<31), block&(1<<31) != 0, false); err != nil {
			return nil, err
		}
	}
	// terrain heights PHP computed since the last sync
	nh := int(r.u8())
	for i := 0; i < nh && r.err == nil; i++ {
		ci := int(r.u8())
		if ci > 8 {
			return nil, errors.New("invalid terrain heights chunk")
		}
		region.SetTerrainHeights(ci, s.readHeights(r))
	}
	nf := int(r.u16())
	type ref struct{ step, index int }
	refs := make([]ref, nf)
	for i := range refs {
		refs[i] = ref{int(r.u8()), int(r.u16())}
	}
	if r.err != nil || len(r.b) != 0 {
		return nil, errors.New("malformed decoration PLACE")
	}
	random := s.random
	random.haveNextNextGaussian = haveGaussian
	random.nextNextGaussian = gaussian
	region.Writes = region.Writes[:0]
	region.BlockEntities = region.BlockEntities[:0]
	region.LogWrites = true
	region.FetchRtBlocks = func(states []int) error {
		w := &wr{}
		w.u8(MsgNeedRt)
		w.u16(uint16(len(states)))
		for _, st := range states {
			w.u16(uint16(st))
		}
		if err := t.Send(w.b); err != nil {
			return transportError{err}
		}
		frame, err := t.Receive()
		if err != nil {
			return transportError{err}
		}
		if len(frame) != 1+2*len(states) || frame[0] != MsgRt {
			return transportError{errors.New("expected RT")}
		}
		for i, st := range states {
			block := int(binary.LittleEndian.Uint16(frame[1+2*i:]))
			if block >= len(s.b.Names) {
				return errors.New("invalid block in RT")
			}
			s.rtBlock[st] = int32(block)
		}
		return nil
	}
	defer func() {
		region.FetchRtBlocks = nil
		region.LogWrites = false
		if p := recover(); p != nil {
			if se, ok := p.(sessionError); ok {
				err = se.err
				return
			}
			err = fmt.Errorf("native feature failed: %v\n%s", p, firstLines(string(debug.Stack()), 12))
		}
	}()
	ctx := s.ctx
	originX := region.CenterChunkX << 4
	originZ := region.CenterChunkZ << 4
	for _, f := range refs {
		if f.step >= len(s.placed) || f.index >= len(s.placed[f.step]) || s.placed[f.step][f.index] == nil {
			return nil, fmt.Errorf("feature %d/%d is not native", f.step, f.index)
		}
		random.SetFeatureSeed(decorationSeed, f.index, f.step)
		s.placed[f.step][f.index].PlaceWithBiomeCheck(ctx, originX, s.minY, originZ)
	}
	if err := s.replicateNativeWrites(t); err != nil {
		return nil, err
	}
	w := &wr{b: s.out[:0]}
	w.u8(MsgDone)
	s.appendWrites(w)
	s.appendLayers(w)
	if random.haveNextNextGaussian {
		w.u8(1)
	} else {
		w.u8(0)
	}
	w.u64(math.Float64bits(random.nextNextGaussian))
	// terrain heights computed here
	n := 0
	for ci := 0; ci < 9; ci++ {
		if region.Computed[ci] {
			n++
		}
	}
	w.u8(byte(n))
	for ci := 0; ci < 9; ci++ {
		if region.Computed[ci] {
			region.Computed[ci] = false
			w.u8(byte(ci))
			h := region.GetTerrainHeights(ci)
			for k := 0; k < 2; k++ {
				for i := 0; i < 256; i++ {
					w.u16(uint16(h[k][i] - int32(s.minY)))
				}
			}
		}
	}
	s.out = w.b
	return w.b, nil
}

// readHeights reads u16[512] terrain heights (WORLD_SURFACE_WG then OCEAN_FLOOR_WG) relative to minY.
func (s *Session) readHeights(r *rd) *[2][256]int32 {
	h := &[2][256]int32{}
	for k := 0; k < 2; k++ {
		for i := 0; i < 256; i++ {
			h[k][i] = int32(r.u16()) + int32(s.minY)
		}
	}
	return h
}

// appendWrites appends u16 b, (u16 length, u8[length] record)[b] block entities, u32 n, u32[n] keys, u16[n] states
// (two arrays: PHP unpacks each with one call). A key with bit 31 set is a block entity: its state is the record index.
func (s *Session) appendWrites(w *wr) {
	w.u16(uint16(len(s.region.BlockEntities)))
	for _, rec := range s.region.BlockEntities {
		w.u16(uint16(len(rec)))
		w.b = append(w.b, rec...)
	}
	writes := s.region.Writes
	w.u32(uint32(len(writes) / 2))
	for i := 0; i < len(writes); i += 2 {
		w.u32(writes[i])
	}
	for i := 1; i < len(writes); i += 2 {
		w.u16(uint16(writes[i]))
	}
}

// pmPosition is the section (chunk index * sections + section) and block index ((x << 8) | (z << 4) | y) of a region
// key (((y - minY) * 48 + dz) * 48 + dx).
func (s *Session) pmPosition(key int) (int, int) {
	dx := key % RegionSize
	dz := (key / RegionSize) % RegionSize
	ry := key / (RegionSize * RegionSize)
	return ((dx>>4)*3+(dz>>4))*s.sections + (ry >> 4), (dx&15)<<8 | (dz&15)<<4 | ry&15
}

// replicateNativeWrites applies the block writes of this batch's native features to the PocketMine layer replica,
// first asking PHP for the PocketMine states it does not know yet (NEED_PM).
func (s *Session) replicateNativeWrites(t Transport) error {
	writes := s.region.Writes
	queue := s.pmQueue[:0]
	for i := 0; i < len(writes); i += 2 {
		if writes[i]&blockEntityWriteBit != 0 {
			continue
		}
		st := int(writes[i+1])
		if s.pmState[st] == -1 {
			s.pmState[st] = -2 // queued
			queue = append(queue, st)
		}
	}
	s.pmQueue = queue
	if len(queue) > 0 {
		w := &wr{}
		w.u8(MsgNeedPm)
		w.u16(uint16(len(queue)))
		for _, st := range queue {
			w.u16(uint16(st))
		}
		if err := t.Send(w.b); err != nil {
			return transportError{err}
		}
		frame, err := t.Receive()
		if err != nil {
			return transportError{err}
		}
		if len(frame) != 1+5*len(queue) || frame[0] != MsgPm {
			return transportError{errors.New("expected PM")}
		}
		for i, st := range queue {
			v := int64(binary.LittleEndian.Uint32(frame[1+5*i:]))
			if frame[5+5*i] != 0 {
				v |= 1 << 32
			}
			s.pmState[st] = v
		}
	}
	for i := 0; i < len(writes); i += 2 {
		if writes[i]&blockEntityWriteBit != 0 {
			continue
		}
		v := s.pmState[writes[i+1]]
		sec, idx := s.pmPosition(int(writes[i]))
		if err := s.pm.write(sec, idx, uint32(v), v>>32 != 0, true); err != nil {
			return err
		}
	}
	return nil
}

// pmDenseWrites is the number of writes of a batch into a section from which the whole section is sent as layers
// (PalettedBlockArray::fromData() in PHP) rather than as single writes (two set() calls each in PHP).
const pmDenseWrites = 12

// appendLayers appends the PocketMine side of this batch's writes (see pmlayers.go):
//
//	u16 chunk mask (region chunks with block writes), u16 s, sections[s]: u16 section (chunk index * sections +
//	section), u8 layers before, (u8 bits, u16 palette size)[2] before (checked by PHP), u8 layers,
//	(u8 bits, u16 p, u32[p] palette, u32[] words)[layers]
//	u32 m, u16[m] section, u16[m] block index ((x << 8) | (z << 4) | y), u32[m] PocketMine state, u8[m] water: the
//	writes into the other sections, in order
func (s *Session) appendLayers(w *wr) {
	p := s.pm
	mask := 0
	dense := 0
	for _, i := range p.touched {
		mask |= 1 << (i / s.sections)
		if sec := &p.sec[i]; !sec.broken && sec.batchWrites >= pmDenseWrites {
			dense++
		}
	}
	w.u16(uint16(mask))
	w.u16(uint16(dense))
	for _, i := range p.touched {
		sec := &p.sec[i]
		if sec.broken || sec.batchWrites < pmDenseWrites {
			continue
		}
		w.u16(uint16(i))
		w.u8(byte(sec.beforeLayers))
		for k := 0; k < 2; k++ {
			if k < sec.beforeLayers {
				w.u8(sec.beforeBits[k])
				w.u16(uint16(sec.beforeCount[k]))
			} else {
				w.u8(0)
				w.u16(0)
			}
		}
		w.u8(byte(sec.layers))
		for k := 0; k < sec.layers; k++ {
			sec.l[k].appendTo(w)
		}
	}
	// single writes
	writes := s.region.Writes
	countAt := len(w.b)
	w.u32(0)
	m := 0
	for pass := 0; pass < 4; pass++ {
		for i := 0; i < len(writes); i += 2 {
			if writes[i]&blockEntityWriteBit != 0 {
				continue
			}
			si, idx := s.pmPosition(int(writes[i]))
			if sec := &p.sec[si]; !sec.broken && sec.batchWrites >= pmDenseWrites {
				continue
			}
			v := s.pmState[writes[i+1]]
			switch pass {
			case 0:
				w.u16(uint16(si))
				m++
			case 1:
				w.u16(uint16(idx))
			case 2:
				w.u32(uint32(v))
			default:
				if v>>32 != 0 {
					w.u8(1)
				} else {
					w.u8(0)
				}
			}
		}
	}
	binary.LittleEndian.PutUint32(w.b[countAt:], uint32(m))
	for _, i := range p.touched {
		p.sec[i].batchWrites = 0
	}
	p.touched = p.touched[:0]
}

func firstLines(s string, n int) string {
	lines := strings.SplitN(s, "\n", n+1)
	if len(lines) > n {
		lines = lines[:n]
	}
	return strings.Join(lines, "\n")
}

// ---- wire helpers ----

type rd struct {
	b   []byte
	err error
}

func (r *rd) take(n int) []byte {
	if r.err != nil || n < 0 || len(r.b) < n {
		r.err = errors.New("truncated message")
		return nil
	}
	v := r.b[:n]
	r.b = r.b[n:]
	return v
}

// peek returns the next byte without consuming it (0 at the end).
func (r *rd) peek() byte {
	if r.err != nil || len(r.b) == 0 {
		return 0
	}
	return r.b[0]
}

func (r *rd) u8() byte {
	if v := r.take(1); v != nil {
		return v[0]
	}
	return 0
}

func (r *rd) u16() uint16 {
	if v := r.take(2); v != nil {
		return binary.LittleEndian.Uint16(v)
	}
	return 0
}

func (r *rd) u32() uint32 {
	if v := r.take(4); v != nil {
		return binary.LittleEndian.Uint32(v)
	}
	return 0
}

func (r *rd) i32() int32 { return int32(r.u32()) }

func (r *rd) u64() uint64 {
	if v := r.take(8); v != nil {
		return binary.LittleEndian.Uint64(v)
	}
	return 0
}

func (r *rd) str() string {
	n := int(r.u16())
	return string(r.take(n))
}

type wr struct{ b []byte }

func (w *wr) u8(v byte)    { w.b = append(w.b, v) }
func (w *wr) u16(v uint16) { w.b = binary.LittleEndian.AppendUint16(w.b, v) }
func (w *wr) u32(v uint32) { w.b = binary.LittleEndian.AppendUint32(w.b, v) }
func (w *wr) u64(v uint64) { w.b = binary.LittleEndian.AppendUint64(w.b, v) }
func (w *wr) str(s string) {
	if len(s) > 0xffff {
		s = s[:0xffff]
	}
	w.u16(uint16(len(s)))
	w.b = append(w.b, s...)
}
