declare(strict_types=1);

namespace pocketmine\loot\bedrock;

use pocketmine\item\enchantment\EnchantingHelper;
use pocketmine\item\Item;
use pocketmine\item\StringToItemParser;
use pocketmine\item\VanillaItems;
use pocketmine\utils\Filesystem;
use pocketmine\utils\Random;
use pocketmine\utils\Utils;
use pocketmine\world\World;
use Symfony\Component\Filesystem\Path;
use function array_key_exists;
use function array_values;
use function count;
use function is_array;
use function is_float;
use function is_int;
use function is_string;
use function json_decode;
use function max;
use function min;
use function mt_rand;
use function str_contains;
use function str_ends_with;
use function str_starts_with;
use function substr;
use const JSON_THROW_ON_ERROR;

/**
 * Bedrock mob equipment loot tables (the "table" of the minecraft:equipment component: zombie_equipment.json,
 * skeleton_gear.json, armor_set_*.json...), shipped in resources/bedrock_equipment_tables.json (generated by
 * tools/generate-bedrock-equipment-tables.php from the behavior pack; do not edit it by hand).
 *
 * Only what those tables use is supported:
 * - pools with "rolls" (a number or {min, max}) of weighted entries, or with "tiers" (initial tier in
 *   [0, initial_range), then +1 for each of "bonus_rolls" passing "bonus_chance");
 * - entries of type "item", "loot_table" (another bundled table) and "empty", and nested "pools" inside an entry (rolled
 *   when the entry is picked: the armor sets give the next piece that way);
 * - conditions random_chance, random_difficulty_chance and random_regional_difficulty_chance (max_chance times the
 *   clamped regional difficulty); any other condition fails;
 * - functions set_count, enchant_random_gear (chance times the clamped regional difficulty, then enchanted like an
 *   enchanting table of level 5 to 5 + 17 x the clamped regional difficulty, like Java mob spawn equipment) and
 *   set_banner_details type 1 (ominous banner); looting_enchant does nothing at spawn; others are ignored.
 *
 * Randomness comes from mt_rand(), so that seeded tests are reproducible.
 */
final class BedrockEquipmentTables{
	public const FILE = "bedrock_equipment_tables.json";

	private const MAX_DEPTH = 16;

	/**
	 * @var mixed[]|null
	 * @phpstan-var array<string, mixed>|null
	 */
	private static ?array $tables = null;
	/** @var Item[] */
	private static array $itemCache = [];

	private function __construct(){
		//NOOP
	}

	/**
	 * Replaces the bundled tables (tests), or restores them (null).
	 *
	 * @param mixed[]|null $tables table name => decoded table JSON
	 * @phpstan-param array<string, mixed>|null $tables
	 */
	public static function setTables(?array $tables) : void{
		self::$tables = $tables;
	}

	/**
	 * @return mixed[]
	 * @phpstan-return array<string, mixed>
	 */
	private static function getTables() : array{
		if(self::$tables === null){
			try{
				$data = json_decode(Filesystem::fileGetContents(Path::join(\pocketmine\RESOURCE_PATH, self::FILE)), true, 512, JSON_THROW_ON_ERROR);
			}catch(\RuntimeException|\JsonException){
				$data = null;
			}
			$tables = [];
			if(is_array($data)){
				foreach(Utils::promoteKeys($data) as $name => $table){
					if(is_string($name)){
						$tables[$name] = $table;
					}
				}
			}
			self::$tables = $tables;
		}
		return self::$tables;
	}

	/**
	 * Returns the full name of a table: "zombie_equipment" and "loot_tables/entities/zombie_equipment.json" both give
	 * the latter.
	 */
	public static function normalizeName(string $name) : string{
		if(!str_contains($name, "/")){
			$name = "loot_tables/entities/" . $name;
		}
		if(!str_ends_with($name, ".json")){
			$name .= ".json";
		}
		return $name;
	}

	public static function has(string $name) : bool{
		return array_key_exists(self::normalizeName($name), self::getTables());
	}

	/**
	 * Rolls an equipment table. Returns the items in the order they were generated (an empty list if the table is
	 * missing).
	 *
	 * @param int   $difficulty        one of the World::DIFFICULTY_* constants
	 * @param float $specialMultiplier clamped regional difficulty (0-1), see
	 *                                 {@link \pocketmine\world\RegionalDifficulty::getSpecialMultiplier()}
	 *
	 * @return Item[]
	 * @phpstan-return list<Item>
	 */
	public static function roll(string $name, int $difficulty, float $specialMultiplier) : array{
		$result = [];
		self::rollTable(self::normalizeName($name), $difficulty, $specialMultiplier, $result, 0);
		return $result;
	}

	/**
	 * @phpstan-param list<Item> $result
	 */
	private static function rollTable(string $name, int $difficulty, float $special, array &$result, int $depth) : void{
		$table = self::getTables()[$name] ?? null;
		if(!is_array($table) || $depth > self::MAX_DEPTH){
			return;
		}
		$pools = $table["pools"] ?? null;
		if(is_array($pools)){
			self::rollPools($pools, $difficulty, $special, $result, $depth);
		}
	}

	/**
	 * @param mixed[] $pools
	 * @phpstan-param list<Item> $result
	 */
	private static function rollPools(array $pools, int $difficulty, float $special, array &$result, int $depth) : void{
		foreach($pools as $pool){
			if(!is_array($pool) || !self::testConditions($pool["conditions"] ?? null, $difficulty, $special)){
				continue;
			}
			$entries = $pool["entries"] ?? null;
			if(!is_array($entries) || count($entries) === 0){
				continue;
			}
			$entries = array_values($entries);
			$tiers = $pool["tiers"] ?? null;
			if(is_array($tiers)){
				$tier = mt_rand(0, max(1, self::intValue($tiers["initial_range"] ?? 1)) - 1);
				$bonusChance = self::floatValue($tiers["bonus_chance"] ?? 0);
				for($i = self::intValue($tiers["bonus_rolls"] ?? 0); $i > 0; --$i){
					if(Utils::getRandomFloat() < $bonusChance){
						++$tier;
					}
				}
				self::rollEntry($entries[min($tier, count($entries) - 1)], $difficulty, $special, $result, $depth);
				continue;
			}
			for($rolls = self::rangeValue($pool["rolls"] ?? 1); $rolls > 0; --$rolls){
				$entry = self::pickWeighted($entries);
				if($entry !== null){
					self::rollEntry($entry, $difficulty, $special, $result, $depth);
				}
			}
		}
	}

	/**
	 * @param mixed[] $entries
	 */
	private static function pickWeighted(array $entries) : mixed{
		$total = 0;
		foreach($entries as $entry){
			$total += is_array($entry) ? max(0, self::intValue($entry["weight"] ?? 1)) : 0;
		}
		if($total <= 0){
			return null;
		}
		$pick = mt_rand(1, $total);
		foreach($entries as $entry){
			if(!is_array($entry)){
				continue;
			}
			$pick -= max(0, self::intValue($entry["weight"] ?? 1));
			if($pick <= 0){
				return $entry;
			}
		}
		return null;
	}

	/**
	 * @phpstan-param list<Item> $result
	 */
	private static function rollEntry(mixed $entry, int $difficulty, float $special, array &$result, int $depth) : void{
		if(!is_array($entry) || !self::testConditions($entry["conditions"] ?? null, $difficulty, $special)){
			return;
		}
		$type = $entry["type"] ?? "item";
		$name = $entry["name"] ?? null;
		if($type === "item" && is_string($name)){
			$item = self::createItem($name);
			if($item !== null){
				$functions = $entry["functions"] ?? null;
				$item = is_array($functions) ? self::applyFunctions($item, $functions, $special) : $item;
				if(!$item->isNull()){
					$result[] = $item;
				}
			}
		}elseif($type === "loot_table" && is_string($name)){
			self::rollTable(self::normalizeName($name), $difficulty, $special, $result, $depth + 1);
		}
		$pools = $entry["pools"] ?? null;
		if(is_array($pools)){
			self::rollPools($pools, $difficulty, $special, $result, $depth + 1);
		}
	}

	private static function createItem(string $name) : ?Item{
		if(!array_key_exists($name, self::$itemCache)){
			$item = StringToItemParser::getInstance()->parse(str_starts_with($name, "minecraft:") ? substr($name, 10) : $name);
			if($item === null){
				return null;
			}
			self::$itemCache[$name] = $item;
		}
		return clone self::$itemCache[$name];
	}

	/**
	 * @param mixed[] $functions
	 */
	private static function applyFunctions(Item $item, array $functions, float $special) : Item{
		foreach($functions as $function){
			if(!is_array($function)){
				continue;
			}
			switch($function["function"] ?? null){
				case "set_count":
					$item->setCount(min($item->getMaxStackSize(), self::rangeValue($function["count"] ?? 1)));
					break;
				case "enchant_random_gear":
					$item = self::enchantRandomGear($item, self::floatValue($function["chance"] ?? 1.0), $special);
					break;
				case "set_banner_details":
					if(self::intValue($function["type"] ?? 0) === 1){
						$item = VanillaItems::OMINOUS_BANNER()->setCount($item->getCount());
					}
					break;
				default:
					//looting_enchant: nothing at spawn
					break;
			}
		}
		return $item;
	}

	/**
	 * Vanilla mob spawn equipment enchanting: with a chance of $chance times the clamped regional difficulty, enchants
	 * the item like an enchanting table of level 5 to 5 + 17 x the clamped regional difficulty (Java
	 * Mob.enchantSpawnedEquipment with the mob_spawn_equipment enchantment provider).
	 */
	public static function enchantRandomGear(Item $item, float $chance, float $specialMultiplier) : Item{
		if($item->isNull() || Utils::getRandomFloat() >= $chance * $specialMultiplier){
			return $item;
		}
		$levels = mt_rand(5, 5 + (int) ($specialMultiplier * 17));
		return EnchantingHelper::enchantWithLevels($item, $levels, new Random(mt_rand()));
	}

	private static function testConditions(mixed $conditions, int $difficulty, float $special) : bool{
		if(!is_array($conditions)){
			return true;
		}
		foreach($conditions as $condition){
			if(!is_array($condition)){
				continue;
			}
			$chance = match($condition["condition"] ?? null){
				"random_chance" => self::floatValue($condition["chance"] ?? 1.0),
				"random_difficulty_chance" => self::floatValue($condition[match($difficulty){
					World::DIFFICULTY_PEACEFUL => "peaceful",
					World::DIFFICULTY_EASY => "easy",
					World::DIFFICULTY_NORMAL => "normal",
					default => "hard"
				}] ?? $condition["default_chance"] ?? 1.0),
				"random_regional_difficulty_chance" => self::floatValue($condition["max_chance"] ?? 1.0) * $special,
				default => 0.0
			};
			if($chance <= 0.0 || ($chance < 1.0 && Utils::getRandomFloat() >= $chance)){
				return false;
			}
		}
		return true;
	}

	private static function intValue(mixed $value) : int{
		return is_int($value) ? $value : (is_float($value) ? (int) $value : 0);
	}

	private static function floatValue(mixed $value) : float{
		return is_int($value) || is_float($value) ? (float) $value : 0.0;
	}

	/**
	 * A number or a {min, max} range (inclusive).
	 */
	private static function rangeValue(mixed $value) : int{
		if(is_array($value)){
			$min = self::intValue($value["min"] ?? 0);
			$max = self::intValue($value["max"] ?? $min);
			return $max > $min ? mt_rand($min, $max) : $min;
		}
		return self::intValue($value);
	}
}
