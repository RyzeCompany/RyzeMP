declare(strict_types=1);

namespace pocketmine\loot\bedrock;

use pocketmine\utils\Filesystem;
use pocketmine\utils\Utils;
use Symfony\Component\Filesystem\Path;
use function array_keys;
use function is_array;
use function is_string;
use function json_decode;
use const JSON_THROW_ON_ERROR;

/**
 * The Bedrock container loot tables (behavior pack chests, dispensers, barrels and pots), shipped in
 * resources/bedrock_loot_tables.json in the Java loot table format, keyed by Java id (generated by
 * tools/generate-bedrock-loot-tables.php with {@link BedrockLootConverter}; do not edit it by hand).
 * {@link \pocketmine\loot\LootTables} rolls them instead of the Java Edition tables of the same name.
 *
 * @internal
 */
final class BedrockLootTables{
	public const FILE = "bedrock_loot_tables.json";

	/**
	 * @var mixed[][]|null
	 * @phpstan-var array<string, mixed[]>|null
	 */
	private static ?array $tables = null;

	private function __construct(){
		//NOOP
	}

	/**
	 * Replaces the bundled tables (tests), or restores them (null).
	 *
	 * @param mixed[][]|null $tables Java id => Java format table
	 * @phpstan-param array<string, mixed[]>|null $tables
	 */
	public static function setTables(?array $tables) : void{
		self::$tables = $tables;
	}

	/**
	 * @return mixed[][]
	 * @phpstan-return array<string, mixed[]>
	 */
	private static function getTables() : array{
		if(self::$tables === null){
			try{
				$data = json_decode(Filesystem::fileGetContents(Path::join(\pocketmine\RESOURCE_PATH, self::FILE)), true, 512, JSON_THROW_ON_ERROR);
			}catch(\RuntimeException|\JsonException $e){
				\GlobalLogger::get()->debug("[Loot] Bedrock loot tables not available: " . $e->getMessage());
				$data = null;
			}
			$tables = [];
			if(is_array($data)){
				foreach(Utils::promoteKeys($data) as $id => $table){
					if(is_string($id) && is_array($table)){
						$tables[$id] = $table;
					}
				}
			}
			self::$tables = $tables;
		}
		return self::$tables;
	}

	/**
	 * The Java format JSON of the Bedrock table with this Java id ("minecraft:chests/buried_treasure"), or null.
	 *
	 * @return mixed[]|null
	 */
	public static function get(string $javaId) : ?array{
		return self::getTables()[$javaId] ?? null;
	}

	/**
	 * Java ids of the bundled tables.
	 * @return string[]
	 * @phpstan-return list<string>
	 */
	public static function getIds() : array{
		return array_keys(self::getTables());
	}
}
