declare(strict_types=1);

namespace pocketmine\command;

use pocketmine\world\Position;

/**
 * A command sender acting for a block (e.g. a command block): target selectors and distances are evaluated from the
 * centre of that block, and there is no executing entity (@s selects nothing).
 */
interface BlockCommandSender extends CommandSender{

	/**
	 * Returns the centre of the block the commands are run by.
	 */
	public function getExecutingPosition() : Position;
}
