declare(strict_types=1);

namespace pocketmine\command;

use pocketmine\entity\Entity;

/**
 * A command sender acting for an entity that isn't a command sender itself (e.g. a command block minecart): target
 * selectors and relative coordinates are evaluated from that entity (@s is the entity).
 */
interface EntityCommandSender extends CommandSender{

	/**
	 * Returns the entity the commands are run as.
	 */
	public function getExecutingEntity() : Entity;
}
