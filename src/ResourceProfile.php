declare(strict_types=1);

namespace pocketmine;

use function is_bool;
use function is_float;
use function is_int;
use function is_string;
use function max;
use function min;
use function strtolower;
use function trim;

/**
 * How the server trades memory and CPU for smoothness (performance-profile in server.properties).
 *
 * Both profiles play exactly the same: same gameplay, mobs, terrain and view distance. They only differ in how much
 * the server keeps in memory or prepares ahead of time:
 * - PERFORMANCE (default) keeps chunks, workers and buffers around so that nothing has to be redone, and the main
 *   thread is rarely interrupted.
 * - ECONOMY gives memory back sooner and keeps fewer helpers running, at the cost of a little more CPU (redoing
 *   things) and latency (new chunks generated by fewer workers, short write stalls during bursts of chunk saves).
 *
 * The values here are defaults: a setting the owner changed in pocketmine.yml wins (see {@link resolveInt()}).
 */
enum ResourceProfile : string{
	case PERFORMANCE = "performance";
	case ECONOMY = "economy";

	/**
	 * Parses a performance-profile value: the profile names and their Spanish aliases (rendimiento, ahorro), any
	 * case. Returns null for anything else.
	 */
	public static function fromString(string $value) : ?self{
		return match(strtolower(trim($value))){
			"performance", "rendimiento" => self::PERFORMANCE,
			"economy", "ahorro" => self::ECONOMY,
			default => null
		};
	}

	/**
	 * Seconds a chunk nobody uses stays loaded before it is unloaded (a player coming back finds it loaded and the
	 * server does not read it from disk again).
	 */
	public function getChunkUnloadDelay() : int{
		return match($this){
			self::PERFORMANCE => 30,
			self::ECONOMY => 10
		};
	}

	/**
	 * LevelDB memtable size of each world, in bytes. A bigger one means fewer level-0 tables and no write throttling
	 * during bursts of chunk saves; it costs up to this much memory per world (twice while a full one is written).
	 */
	public function getLevelDBWriteBufferSize() : int{
		return match($this){
			self::PERFORMANCE => 16 * 1024 * 1024,
			self::ECONOMY => 4 * 1024 * 1024
		};
	}

	/**
	 * Upper bound of settings.async-workers "auto" (still at most the usable cores - 2, at least 2).
	 */
	public function getMaxAutoAsyncWorkers() : int{
		return match($this){
			self::PERFORMANCE => Server::MAX_AUTO_ASYNC_WORKERS,
			self::ECONOMY => 2
		};
	}

	/**
	 * Number of async workers of settings.async-workers "auto" for this many usable cores: cores - 2, at least 2 (one
	 * worker would run generation, lighting and chunk sending one after another), at most
	 * {@link getMaxAutoAsyncWorkers()}.
	 */
	public function getAutoAsyncWorkerCount(int $usableCores) : int{
		return min($this->getMaxAutoAsyncWorkers(), max(2, $usableCores - 2));
	}

	/**
	 * chunk-generation.max-workers: async workers that generate chunks, each holding its own copy of the vanilla
	 * generator (~130 MB). Fewer means chunks far from the players arrive later, not different chunks.
	 */
	public function getChunkGenerationWorkers() : int{
		return match($this){
			self::PERFORMANCE => 2,
			self::ECONOMY => 1
		};
	}

	/**
	 * memory.async-worker-idle-timeout: seconds without tasks after which an async worker is shut down.
	 */
	public function getAsyncWorkerIdleTimeout() : int{
		return match($this){
			self::PERFORMANCE => 300,
			self::ECONOMY => 60
		};
	}

	/**
	 * GOGC of the vanillagen helper process (Go's default is 100: the heap may grow to twice the live data before a
	 * collection), or null to leave it to Go. A GOGC the owner set in the environment is always kept.
	 */
	public function getVanillagenGoGc() : ?int{
		return match($this){
			self::PERFORMANCE => null,
			self::ECONOMY => 50
		};
	}

	/**
	 * Reads an integer pocketmine.yml setting that has a default in the profile. The profile's value is used when the
	 * setting is missing or still has the value shipped in pocketmine.yml ($shipped, the PERFORMANCE value):
	 * pocketmine.yml is written with every default when the server first starts, so a value equal to the shipped one
	 * cannot be told apart from a value nobody changed. Any other value is the owner's choice and wins.
	 *
	 * @internal
	 */
	public function resolveInt(ServerConfigGroup $config, string $key, int $shipped, int $profileValue) : int{
		$value = $config->getProperty($key);
		if($value === null){
			return $profileValue;
		}
		if(is_int($value) || is_float($value) || is_bool($value) || is_string($value)){
			$int = (int) $value;
			return $int === $shipped ? $profileValue : $int;
		}
		return $profileValue;
	}
}
