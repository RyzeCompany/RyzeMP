declare(strict_types=1);

namespace pocketmine\block;

use pocketmine\block\utils\BoneMealSpread;
use pocketmine\block\utils\StaticSupportTrait;
use pocketmine\item\Fertilizer;
use pocketmine\item\Item;
use pocketmine\math\Facing;
use pocketmine\math\Vector3;
use pocketmine\player\Player;

/**
 * Firefly bush (Bedrock 1.21.80): a light-emitting (level 2) plant that grows on dirt-like blocks.
 * The firefly particles are rendered by the client; bone meal places another firefly bush next to it.
 */
class FireflyBush extends Flowable{
	use StaticSupportTrait;

	public function getLightLevel() : int{
		return 2;
	}

	private function canBeSupportedAt(Block $block) : bool{
		$supportBlock = $block->getSide(Facing::DOWN);
		return $supportBlock->hasTypeTag(BlockTypeTags::DIRT) || $supportBlock->hasTypeTag(BlockTypeTags::MUD);
	}

	public function onInteract(Item $item, int $face, Vector3 $clickVector, ?Player $player = null, array &$returnedItems = []) : bool{
		//bone meal places a copy on a free neighbour (vanilla BushBlock.performBonemeal())
		return $item instanceof Fertilizer && BoneMealSpread::placeOnNeighbour($this, clone $this, $item, $player);
	}

	public function getFlameEncouragement() : int{
		return 60;
	}

	public function getFlammability() : int{
		return 100;
	}

	public function getCompostabilityChance() : int{
		return 30;
	}
}
