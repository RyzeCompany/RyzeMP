/**
 * Block entity of a structure block (Bedrock ID "StructureBlock", same fields and defaults as BDS 1.26.52). In save
 * mode it saves the box at its offset and size as a structure template of the world (see
 * {@link StructureTemplateStorage}); in load mode it loads the template of its name at its offset, with its rotation,
 * mirror, integrity, seed and animation; in corner mode it marks a corner of the area found by
 * {@link StructureBlock::detectSize()}; data mode only holds a text for the structures generated by the game. A
 * redstone signal turning on saves (in memory or to disk, as its redstone save mode says) or loads.
 *
 * "isPowered" is the redstone state in the saved data (like Java's "powered"), so that a block still powered when its
 * chunk loads again doesn't see a new signal; clients always get false, like BDS sends.
 */
class StructureBlock extends Spawnable{
	public const TAG_STRUCTURE_NAME = "structureName";
	public const TAG_DATA_FIELD = "dataField";
	public const TAG_MODE = "data";
	public const TAG_REDSTONE_SAVE_MODE = "redstoneSaveMode";
	public const TAG_OFFSET_X = "xStructureOffset";
	public const TAG_OFFSET_Y = "yStructureOffset";
	public const TAG_OFFSET_Z = "zStructureOffset";
	public const TAG_SIZE_X = "xStructureSize";
	public const TAG_SIZE_Y = "yStructureSize";
	public const TAG_SIZE_Z = "zStructureSize";
	public const TAG_IGNORE_ENTITIES = "ignoreEntities";
	public const TAG_INCLUDE_PLAYERS = "includePlayers";
	public const TAG_REMOVE_BLOCKS = "removeBlocks";
	public const TAG_SHOW_BOUNDING_BOX = "showBoundingBox";
	public const TAG_ROTATION = "rotation";
	public const TAG_MIRROR = "mirror";
	public const TAG_INTEGRITY = "integrity";
	public const TAG_SEED = "seed";
	public const TAG_ANIMATION_MODE = "animationMode";
	public const TAG_ANIMATION_SECONDS = "animationSeconds";
	public const TAG_IS_POWERED = "isPowered";
	public const TAG_LAST_TOUCHED_PLAYER_ID = "lastTouchedPlayerId";

	public const REDSTONE_SAVE_MEMORY = 0;
	public const REDSTONE_SAVE_DISK = 1;

	public const MAX_SIZE_X = 64;
	public const MAX_SIZE_Y = 384;
	public const MAX_SIZE_Z = 64;
	public const MAX_OFFSET_X = 64;
	public const MAX_OFFSET_Y = 384;
	public const MAX_OFFSET_Z = 64;
	public const MAX_NAME_LENGTH = 128;
	public const MAX_ANIMATION_SECONDS = 3600.0;
	/** Horizontal distance searched for corner blocks (vanilla StructureBlockEntity.SCAN_CORNER_BLOCKS_RANGE) */
	public const CORNER_SCAN_RANGE = 80;

	private StructureBlockType $mode = StructureBlockType::SAVE;
	private string $structureName = "";
	private string $dataField = "";
	private int $redstoneSaveMode = self::REDSTONE_SAVE_MEMORY;
	private int $offsetX = 0;
	private int $offsetY = -1;
	private int $offsetZ = 0;
	private int $sizeX = 5;
	private int $sizeY = 5;
	private int $sizeZ = 5;
	private bool $ignoreEntities = false;
	private bool $includePlayers = false;
	private bool $removeBlocks = false;
	private bool $showBoundingBox = true;
	private StructureRotation $rotation = StructureRotation::NONE;
	private StructureMirror $mirror = StructureMirror::NONE;
	private float $integrity = 100.0;
	private int $seed = 0;
	private int $animationMode = StructurePlaceSettings::ANIMATION_NONE;
	private float $animationSeconds = 0.0;
	private int $lastTouchedPlayerId = -1;

	/** Whether a redstone signal reaches the block */
	private bool $powered = false;
	private ?StructurePlacementTask $placement = null;

	/**
	 * @internal Bedrock ID of a mode ("data" of the block entity, structure block type of the screen's packets).
	 */
	public static function modeToId(StructureBlockType $mode) : int{
		return match($mode){
			StructureBlockType::DATA => 0,
			StructureBlockType::SAVE => 1,
			StructureBlockType::LOAD => 2,
			StructureBlockType::CORNER => 3,
			StructureBlockType::INVALID => 4,
			StructureBlockType::EXPORT => 5,
		};
	}

	/**
	 * @internal Mode of a Bedrock ID, or null if there is none.
	 */
	public static function modeFromId(int $id) : ?StructureBlockType{
		return match($id){
			0 => StructureBlockType::DATA,
			1 => StructureBlockType::SAVE,
			2 => StructureBlockType::LOAD,
			3 => StructureBlockType::CORNER,
			4 => StructureBlockType::INVALID,
			5 => StructureBlockType::EXPORT,
			default => null
		};
	}

	/**
	 * Whether the name can be used as a structure template name: not empty, printable, at most MAX_NAME_LENGTH long.
	 */
	public static function isValidStructureName(string $name) : bool{
		return $name !== "" && mb_strlen($name) <= self::MAX_NAME_LENGTH && preg_match('/[\x00-\x1f\x7f]/u', $name) === 0;
	}

	public function readSaveData(CompoundTag $nbt) : void{
		if(($tag = $nbt->getTag(self::TAG_MODE)) instanceof IntTag && ($mode = self::modeFromId($tag->getValue())) !== null){
			$this->mode = $mode;
		}
		if(($tag = $nbt->getTag(self::TAG_STRUCTURE_NAME)) instanceof StringTag){
			$this->structureName = $tag->getValue();
		}
		if(($tag = $nbt->getTag(self::TAG_DATA_FIELD)) instanceof StringTag){
			$this->dataField = $tag->getValue();
		}
		if(($tag = $nbt->getTag(self::TAG_REDSTONE_SAVE_MODE)) instanceof IntTag){
			$this->redstoneSaveMode = $tag->getValue() === self::REDSTONE_SAVE_DISK ? self::REDSTONE_SAVE_DISK : self::REDSTONE_SAVE_MEMORY;
		}
		$this->setOffset(
			$nbt->getInt(self::TAG_OFFSET_X, $this->offsetX),
			$nbt->getInt(self::TAG_OFFSET_Y, $this->offsetY),
			$nbt->getInt(self::TAG_OFFSET_Z, $this->offsetZ)
		);
		$this->setSize(
			$nbt->getInt(self::TAG_SIZE_X, $this->sizeX),
			$nbt->getInt(self::TAG_SIZE_Y, $this->sizeY),
			$nbt->getInt(self::TAG_SIZE_Z, $this->sizeZ)
		);
		$this->ignoreEntities = self::readBool($nbt, self::TAG_IGNORE_ENTITIES, $this->ignoreEntities);
		$this->includePlayers = self::readBool($nbt, self::TAG_INCLUDE_PLAYERS, $this->includePlayers);
		$this->removeBlocks = self::readBool($nbt, self::TAG_REMOVE_BLOCKS, $this->removeBlocks);
		$this->showBoundingBox = self::readBool($nbt, self::TAG_SHOW_BOUNDING_BOX, $this->showBoundingBox);
		if(($tag = $nbt->getTag(self::TAG_ROTATION)) instanceof ByteTag){
			$this->rotation = StructureRotation::tryFrom($tag->getValue()) ?? StructureRotation::NONE;
		}
		if(($tag = $nbt->getTag(self::TAG_MIRROR)) instanceof ByteTag){
			$this->mirror = StructureMirror::tryFrom($tag->getValue()) ?? StructureMirror::NONE;
		}
		if(($tag = $nbt->getTag(self::TAG_INTEGRITY)) instanceof FloatTag){
			$this->setIntegrity($tag->getValue());
		}
		if(($tag = $nbt->getTag(self::TAG_SEED)) instanceof LongTag){
			$this->seed = $tag->getValue();
		}
		if(($tag = $nbt->getTag(self::TAG_ANIMATION_MODE)) instanceof ByteTag){
			$this->setAnimationMode($tag->getValue());
		}
		if(($tag = $nbt->getTag(self::TAG_ANIMATION_SECONDS)) instanceof FloatTag){
			$this->setAnimationSeconds($tag->getValue());
		}
		if(($tag = $nbt->getTag(self::TAG_LAST_TOUCHED_PLAYER_ID)) instanceof LongTag){
			$this->lastTouchedPlayerId = $tag->getValue();
		}
		$this->powered = self::readBool($nbt, self::TAG_IS_POWERED, $this->powered);
	}

	private static function readBool(CompoundTag $nbt, string $name, bool $default) : bool{
		$tag = $nbt->getTag($name);
		return $tag instanceof ByteTag ? $tag->getValue() !== 0 : $default;
	}

	protected function writeSaveData(CompoundTag $nbt) : void{
		$this->writeStructureData($nbt, $this->powered);
	}

	protected function addAdditionalSpawnData(CompoundTag $nbt) : void{
		$this->writeStructureData($nbt, false);
	}

	private function writeStructureData(CompoundTag $nbt, bool $powered) : void{
		$nbt->setByte(self::TAG_ANIMATION_MODE, $this->animationMode);
		$nbt->setFloat(self::TAG_ANIMATION_SECONDS, $this->animationSeconds);
		$nbt->setInt(self::TAG_MODE, self::modeToId($this->mode));
		$nbt->setString(self::TAG_DATA_FIELD, $this->dataField);
		$nbt->setByte(self::TAG_IGNORE_ENTITIES, $this->ignoreEntities ? 1 : 0);
		$nbt->setByte(self::TAG_INCLUDE_PLAYERS, $this->includePlayers ? 1 : 0);
		$nbt->setFloat(self::TAG_INTEGRITY, $this->integrity);
		$nbt->setByte(self::TAG_IS_POWERED, $powered ? 1 : 0);
		$nbt->setLong(self::TAG_LAST_TOUCHED_PLAYER_ID, $this->lastTouchedPlayerId);
		$nbt->setByte(self::TAG_MIRROR, $this->mirror->value);
		$nbt->setInt(self::TAG_REDSTONE_SAVE_MODE, $this->redstoneSaveMode);
		$nbt->setByte(self::TAG_REMOVE_BLOCKS, $this->removeBlocks ? 1 : 0);
		$nbt->setByte(self::TAG_ROTATION, $this->rotation->value);
		$nbt->setLong(self::TAG_SEED, $this->seed);
		$nbt->setByte(self::TAG_SHOW_BOUNDING_BOX, $this->showBoundingBox ? 1 : 0);
		$nbt->setString(self::TAG_STRUCTURE_NAME, $this->structureName);
		$nbt->setInt(self::TAG_OFFSET_X, $this->offsetX);
		$nbt->setInt(self::TAG_SIZE_X, $this->sizeX);
		$nbt->setInt(self::TAG_OFFSET_Y, $this->offsetY);
		$nbt->setInt(self::TAG_SIZE_Y, $this->sizeY);
		$nbt->setInt(self::TAG_OFFSET_Z, $this->offsetZ);
		$nbt->setInt(self::TAG_SIZE_Z, $this->sizeZ);
	}

	public function getMode() : StructureBlockType{ return $this->mode; }

	/**
	 * Sets the mode of the block entity only: use {@link BlockStructureBlock::setMode()} to change the block (which
	 * updates its block entity).
	 */
	public function setMode(StructureBlockType $mode) : void{ $this->mode = $mode; }

	public function getStructureName() : string{ return $this->structureName; }

	public function setStructureName(string $name) : void{ $this->structureName = $name; }

	public function getDataField() : string{ return $this->dataField; }

	public function setDataField(string $dataField) : void{ $this->dataField = $dataField; }

	public function getRedstoneSaveMode() : int{ return $this->redstoneSaveMode; }

	public function setRedstoneSaveMode(int $mode) : void{
		$this->redstoneSaveMode = $mode === self::REDSTONE_SAVE_DISK ? self::REDSTONE_SAVE_DISK : self::REDSTONE_SAVE_MEMORY;
	}

	public function getOffset() : Vector3{ return new Vector3($this->offsetX, $this->offsetY, $this->offsetZ); }

	/**
	 * Sets the offset of the structure from the block, clamped to the vanilla limits.
	 */
	public function setOffset(int $x, int $y, int $z) : void{
		$this->offsetX = max(-self::MAX_OFFSET_X, min(self::MAX_OFFSET_X, $x));
		$this->offsetY = max(-self::MAX_OFFSET_Y, min(self::MAX_OFFSET_Y, $y));
		$this->offsetZ = max(-self::MAX_OFFSET_Z, min(self::MAX_OFFSET_Z, $z));
	}

	public function getSize() : Vector3{ return new Vector3($this->sizeX, $this->sizeY, $this->sizeZ); }

	/**
	 * Sets the size of the structure, clamped to the vanilla limits (0 to 64x384x64).
	 */
	public function setSize(int $x, int $y, int $z) : void{
		$this->sizeX = max(0, min(self::MAX_SIZE_X, $x));
		$this->sizeY = max(0, min(self::MAX_SIZE_Y, $y));
		$this->sizeZ = max(0, min(self::MAX_SIZE_Z, $z));
	}

	public function isIgnoreEntities() : bool{ return $this->ignoreEntities; }

	public function setIgnoreEntities(bool $ignoreEntities) : void{ $this->ignoreEntities = $ignoreEntities; }

	public function isIncludePlayers() : bool{ return $this->includePlayers; }

	public function setIncludePlayers(bool $includePlayers) : void{ $this->includePlayers = $includePlayers; }

	public function isRemoveBlocks() : bool{ return $this->removeBlocks; }

	public function setRemoveBlocks(bool $removeBlocks) : void{ $this->removeBlocks = $removeBlocks; }

	public function isShowBoundingBox() : bool{ return $this->showBoundingBox; }

	public function setShowBoundingBox(bool $showBoundingBox) : void{ $this->showBoundingBox = $showBoundingBox; }

	public function getRotation() : StructureRotation{ return $this->rotation; }

	public function setRotation(StructureRotation $rotation) : void{ $this->rotation = $rotation; }

	public function getMirror() : StructureMirror{ return $this->mirror; }

	public function setMirror(StructureMirror $mirror) : void{ $this->mirror = $mirror; }

	public function getIntegrity() : float{ return $this->integrity; }

	public function setIntegrity(float $integrity) : void{
		$this->integrity = is_finite($integrity) ? max(0.0, min(100.0, $integrity)) : 100.0;
	}

	public function getSeed() : int{ return $this->seed; }

	public function setSeed(int $seed) : void{ $this->seed = $seed; }

	public function getAnimationMode() : int{ return $this->animationMode; }

	public function setAnimationMode(int $mode) : void{
		$this->animationMode = $mode >= StructurePlaceSettings::ANIMATION_NONE && $mode <= StructurePlaceSettings::ANIMATION_BY_BLOCK ? $mode : StructurePlaceSettings::ANIMATION_NONE;
	}

	public function getAnimationSeconds() : float{ return $this->animationSeconds; }

	public function setAnimationSeconds(float $seconds) : void{
		$this->animationSeconds = is_finite($seconds) ? max(0.0, min(self::MAX_ANIMATION_SECONDS, $seconds)) : 0.0;
	}

	public function getLastTouchedPlayerId() : int{ return $this->lastTouchedPlayerId; }

	public function setLastTouchedPlayerId(int $id) : void{ $this->lastTouchedPlayerId = $id; }

	/**
	 * Whether a structure is being loaded by this block (big or animated structures take several ticks).
	 */
	public function isLoadingStructure() : bool{
		return $this->placement !== null;
	}

	/**
	 * Saves or loads, as the screen's Save and Load buttons do (saves always go to disk). Returns an error message, or
	 * null if it worked.
	 */
	public function trigger() : ?Translatable{
		return match($this->mode){
			StructureBlockType::SAVE => $this->saveStructure(true),
			StructureBlockType::LOAD => $this->loadStructure(),
			default => null
		};
	}

	/**
	 * Called when the redstone signal reaching the block changes: when it turns on, saves (as the redstone save mode
	 * says) or loads.
	 */
	public function onRedstoneSignal(bool $powered) : void{
		if($powered === $this->powered){
			return;
		}
		$this->powered = $powered;
		if($powered){
			match($this->mode){
				StructureBlockType::SAVE => $this->saveStructure($this->redstoneSaveMode === self::REDSTONE_SAVE_DISK),
				StructureBlockType::LOAD => $this->loadStructure(),
				default => null
			};
		}
	}

	/**
	 * Saves the box at the block's offset and size as the template of its name. Returns an error message, or null if
	 * it worked.
	 */
	public function saveStructure(bool $toDisk) : ?Translatable{
		if(!self::isValidStructureName($this->structureName)){
			return new Translatable("commands.structure.invalid.name");
		}
		if($this->sizeX < 1 || $this->sizeY < 1 || $this->sizeZ < 1){
			return new Translatable("commands.structure.size.tooSmall", ["1", "1", "1", (string) $this->sizeX, (string) $this->sizeY, (string) $this->sizeZ]);
		}
		$world = $this->position->getWorld();
		$origin = $this->position->addVector($this->getOffset());
		$template = StructureTemplateBuilder::fromWorld(
			$world,
			$origin->getFloorX(), $origin->getFloorY(), $origin->getFloorZ(),
			$this->sizeX, $this->sizeY, $this->sizeZ,
			!$this->ignoreEntities,
			!$this->removeBlocks
		);
		if($template->isEmpty()){
			return new Translatable("commands.structure.empty.save");
		}
		StructureTemplateStorage::get($world)->save($this->structureName, $template, $toDisk);
		return null;
	}

	/**
	 * Loads the template of the block's name at its offset, with its settings. Big or animated structures are loaded
	 * over several ticks. Returns an error message, or null if it worked (or started).
	 */
	public function loadStructure() : ?Translatable{
		if($this->placement !== null){
			return null;
		}
		if(!self::isValidStructureName($this->structureName)){
			return new Translatable("commands.structure.invalid.name");
		}
		$world = $this->position->getWorld();
		try{
			$template = StructureTemplateStorage::get($world)->load($this->structureName);
		}catch(StructureTemplateException){
			return new Translatable("commands.structure.error");
		}
		if($template === null){
			return new Translatable("commands.structure.notFound", [$this->structureName]);
		}
		if($template->isEmpty()){
			return new Translatable("commands.structure.empty.load");
		}
		$origin = $this->position->addVector($this->getOffset());
		$placer = new StructurePlacer($template, $origin->getFloorX(), $origin->getFloorY(), $origin->getFloorZ(), new StructurePlaceSettings(
			$this->mirror,
			$this->rotation,
			!$this->ignoreEntities,
			!$this->removeBlocks,
			$this->integrity,
			$this->seed,
			$this->animationMode,
			$this->animationSeconds
		));
		$task = new StructurePlacementTask($world, $placer, $this->position);
		if(!$task->prepare()){
			return new Translatable("commands.structure.unloadedChunks");
		}

		//like vanilla, the size shown by the block becomes the size of the template loaded
		$this->setSize($template->getSizeX(), $template->getSizeY(), $template->getSizeZ());
		$this->clearSpawnCompoundCache();
		$block = $world->getBlock($this->position);
		if($block instanceof BlockStructureBlock){
			$world->setBlock($this->position, $block);
		}

		if(!$task->run()){
			if($this->closed){
				//something replaced this block (the structure itself does it last): nothing will drive the task any more
				$task->finish();
			}else{
				$this->placement = $task;
				$world->scheduleDelayedBlockUpdate($this->position, 1);
			}
		}
		return null;
	}

	/**
	 * @internal Called by the block every tick while a structure is being loaded.
	 */
	public function continuePlacement() : void{
		$placement = $this->placement;
		if($placement === null){
			return;
		}
		if($placement->run()){
			$this->placement = null;
		}elseif(!$this->closed){
			$this->position->getWorld()->scheduleDelayedBlockUpdate($this->position, 1);
		}
	}

	/**
	 * Finds the corner blocks with the same structure name around the block (the screen's Detect button in save mode)
	 * and sets the offset and size to the area between them. Returns whether an area was found.
	 */
	public function detectSize() : bool{
		if($this->mode !== StructureBlockType::SAVE || !self::isValidStructureName($this->structureName)){
			return false;
		}
		$world = $this->position->getWorld();
		$selfX = $this->position->getFloorX();
		$selfZ = $this->position->getFloorZ();
		$corners = [];
		for($chunkX = ($selfX - self::CORNER_SCAN_RANGE) >> Chunk::COORD_BIT_SIZE; $chunkX <= ($selfX + self::CORNER_SCAN_RANGE) >> Chunk::COORD_BIT_SIZE; ++$chunkX){
			for($chunkZ = ($selfZ - self::CORNER_SCAN_RANGE) >> Chunk::COORD_BIT_SIZE; $chunkZ <= ($selfZ + self::CORNER_SCAN_RANGE) >> Chunk::COORD_BIT_SIZE; ++$chunkZ){
				foreach($world->getChunk($chunkX, $chunkZ)?->getTiles() ?? [] as $tile){
					if($tile !== $this && $tile instanceof self && !$tile->closed && $tile->mode === StructureBlockType::CORNER && $tile->structureName === $this->structureName){
						$pos = $tile->position;
						if($pos->x >= $selfX - self::CORNER_SCAN_RANGE && $pos->x <= $selfX + self::CORNER_SCAN_RANGE && $pos->z >= $selfZ - self::CORNER_SCAN_RANGE && $pos->z <= $selfZ + self::CORNER_SCAN_RANGE){
							$corners[] = $pos->asVector3();
						}
					}
				}
			}
		}
		$area = self::computeCornerArea($this->position->asVector3(), $corners);
		if($area === null){
			return false;
		}
		[$offset, $size] = $area;
		$this->setOffset($offset->getFloorX(), $offset->getFloorY(), $offset->getFloorZ());
		$this->setSize($size->getFloorX(), $size->getFloorY(), $size->getFloorZ());
		return true;
	}

	/**
	 * Vanilla StructureBlockEntity.detectSize(): the box enclosing the corner blocks (and the block itself when there
	 * is only one corner); the structure is the inside of the box, which must be at least one block in every
	 * direction. Returns the offset from the block and the size, or null.
	 *
	 * @internal
	 *
	 * @param Vector3[] $corners
	 * @phpstan-param list<Vector3> $corners
	 * @return Vector3[]|null
	 * @phpstan-return array{Vector3, Vector3}|null
	 */
	public static function computeCornerArea(Vector3 $self, array $corners) : ?array{
		if(count($corners) === 0){
			return null;
		}
		$points = count($corners) === 1 ? [$corners[0], $self] : $corners;
		$min = Vector3::minComponents(...$points);
		$max = Vector3::maxComponents(...$points);
		$dx = $max->getFloorX() - $min->getFloorX();
		$dy = $max->getFloorY() - $min->getFloorY();
		$dz = $max->getFloorZ() - $min->getFloorZ();
		if($dx <= 1 || $dy <= 1 || $dz <= 1){
			return null;
		}
		return [
			new Vector3($min->getFloorX() - $self->getFloorX() + 1, $min->getFloorY() - $self->getFloorY() + 1, $min->getFloorZ() - $self->getFloorZ() + 1),
			new Vector3($dx - 1, $dy - 1, $dz - 1)
		];
	}

	public function close() : void{
		if(!$this->closed && $this->placement !== null){
			//the block went away while it was loading a structure: finish the structure now (when the structure
			//replaces the block, which it does last, only its entities are left)
			$placement = $this->placement;
			$this->placement = null;
			$placement->finish();
		}
		parent::close();
	}
}
