declare(strict_types=1);

namespace pocketmine\block\utils;

/**
 * Implemented by entities which activate detector rails: in vanilla, only minecarts do (see
 * {@link \pocketmine\entity\vehicle\AbstractMinecart}).
 */
interface DetectorRailActivator{

	/**
	 * Returns the signal strength (0-15) a comparator reading a detector rail with this entity on it outputs (the fill
	 * level of a container minecart, 0 for a plain minecart).
	 */
	public function getDetectorRailComparatorOutput() : int;
}
