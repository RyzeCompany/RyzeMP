declare(strict_types=1);

namespace pocketmine\block\utils;

/**
 * Shape of redstone dust towards one horizontal side (Bedrock 1.26.60+ redstone_{north,east,south,west} states).
 */
enum RedstoneWireConnection{
	/** Not connected on this side */
	case NONE;
	/** Connected to something at the same height (or to dust one block lower) */
	case SIDE;
	/** Connected to dust one block higher, running up the side of the neighbouring block */
	case UP;
}
