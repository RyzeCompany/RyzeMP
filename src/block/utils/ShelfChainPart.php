namespace pocketmine\block\utils;

/**
 * Position of a powered shelf inside a chain of up to three connected shelves, as seen by a player facing the
 * shelves' front. Stored in the Bedrock powered_shelf_type state (0 = unconnected, 1 = right, 2 = center,
 * 3 = left, following the order of the Java side_chain property).
 */
enum ShelfChainPart{
	case UNCONNECTED;
	case RIGHT;
	case CENTER;
	case LEFT;
}
