declare(strict_types=1);

namespace pocketmine\block\utils;

/**
 * Kind of a command block: each one is a different block (command_block, repeating_command_block and
 * chain_command_block). The values are the modes of the command block screen (CommandBlockUpdatePacket).
 */
enum CommandBlockType : int{
	/** Runs once when activated. */
	case IMPULSE = 0;
	/** Runs every TickDelay ticks while active. */
	case REPEATING = 1;
	/** Runs when the command block pointing into it has run. */
	case CHAIN = 2;
}
