declare(strict_types=1);

namespace pocketmine\world\mobs\spawn;

use pocketmine\utils\Filesystem;
use pocketmine\utils\Utils;
use Symfony\Component\Filesystem\Path;
use function array_key_exists;
use function is_array;
use function is_bool;
use function is_int;
use function is_string;
use function json_decode;
use function json_encode;
use const JSON_PRETTY_PRINT;
use const JSON_THROW_ON_ERROR;
use const JSON_UNESCAPED_SLASHES;

/**
 * Compact table of the vanilla spawn rules shipped in resources/vanilla_spawn_rules.json: the {@link SpawnCondition}s
 * and populations derived by VanillaMine from Mojang's files, as plain values. RyzeMP uses the registered subset
 * without downloading files during a server tick.
 *
 * Generated by VanillaMine's tools/generate-vanilla-spawn-rules.php from Mojang's pinned Bedrock samples; do not
 * edit the JSON by hand. Only the values differing from the constructor defaults are stored.
 */
final class BundledSpawnRules{
	public const FILE = "vanilla_spawn_rules.json";
	public const TAG = "v1.26.50.4";

	private static ?SpawnRules $rules = null;
	private static bool $loaded = false;

	private function __construct(){
		//NOOP
	}

	/**
	 * Returns the bundled rules (read once), or null if the file is missing, damaged or made for another Bedrock
	 * version than {@link BundledSpawnRules::TAG}.
	 */
	public static function get() : ?SpawnRules{
		if(!self::$loaded){
			self::$loaded = true;
			try{
				self::$rules = self::loadFile(Path::join(\pocketmine\RESOURCE_PATH, self::FILE));
			}catch(\InvalidArgumentException|\RuntimeException|\JsonException){
				self::$rules = null;
			}
		}
		return self::$rules;
	}

	/**
	 * @throws \InvalidArgumentException|\RuntimeException|\JsonException
	 */
	public static function loadFile(string $path) : ?SpawnRules{
		$data = json_decode(Filesystem::fileGetContents($path), true, 64, JSON_THROW_ON_ERROR);
		if(!is_array($data)){
			throw new \InvalidArgumentException("Invalid bundled spawn rules");
		}
		return self::decode($data);
	}

	/**
	 * Converts rules to the bundled format (generator).
	 *
	 * @return mixed[]
	 * @phpstan-return array{tag: string, populations: array<string, string>, conditions: list<array<string, mixed>>}
	 */
	public static function encode(SpawnRules $rules) : array{
		$conditions = [];
		foreach($rules->getConditions() as $condition){
			$conditions[] = self::encodeObject($condition);
		}
		$populations = $rules->getPopulations();
		return ["tag" => self::TAG, "populations" => $populations, "conditions" => $conditions];
	}

	/**
	 * @throws \JsonException
	 */
	public static function toJson(SpawnRules $rules) : string{
		return json_encode(self::encode($rules), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR) . "\n";
	}

	/**
	 * @return mixed[]
	 * @phpstan-return array<string, mixed>
	 */
	private static function encodeObject(SpawnCondition|SpawnHerd $object) : array{
		$result = [];
		$constructor = (new \ReflectionClass($object))->getConstructor();
		if($constructor === null){
			return $result;
		}
		foreach($constructor->getParameters() as $parameter){
			$name = $parameter->getName();
			$value = (new \ReflectionProperty($object, $name))->getValue($object);
			if($parameter->isDefaultValueAvailable() && $parameter->getDefaultValue() === $value){
				continue;
			}
			if($name === "herds" && is_array($value)){
				$herds = [];
				foreach($value as $herd){
					if($herd instanceof SpawnHerd){
						$herds[] = self::encodeObject($herd);
					}
				}
				$value = $herds;
			}
			$result[$name] = $value;
		}
		return $result;
	}

	/**
	 * Reads rules in the bundled format; null if they were made for another Bedrock version.
	 *
	 * @param mixed[] $data
	 *
	 * @throws \InvalidArgumentException
	 */
	public static function decode(array $data) : ?SpawnRules{
		if(($data["tag"] ?? null) !== self::TAG){
			return null;
		}
		$populations = [];
		foreach(Utils::promoteKeys(self::arr($data, "populations")) as $identifier => $population){
			if(!is_string($identifier) || !is_string($population)){
				throw new \InvalidArgumentException("Invalid population entry");
			}
			$populations[$identifier] = $population;
		}
		$conditions = [];
		foreach(self::arr($data, "conditions") as $c){
			if(!is_array($c)){
				throw new \InvalidArgumentException("Invalid condition");
			}
			$herds = [];
			foreach(self::arr($c, "herds", []) as $h){
				if(!is_array($h)){
					throw new \InvalidArgumentException("Invalid herd");
				}
				$herds[] = new SpawnHerd(
					self::int($h, "minSize"),
					self::int($h, "maxSize"),
					self::optString($h, "event"),
					self::optInt($h, "eventSkipCount") ?? 0,
					self::optString($h, "initialEvent"),
					self::optInt($h, "initialEventCount") ?? 0
				);
			}
			$permuteTypes = [];
			foreach(self::arr($c, "permuteTypes", []) as $permute){
				if(!is_array($permute) || !array_key_exists(0, $permute) || !array_key_exists(1, $permute) || ($permute[0] !== null && !is_string($permute[0])) || !is_int($permute[1])){
					throw new \InvalidArgumentException("Invalid permute type");
				}
				$permuteTypes[] = [$permute[0], $permute[1]];
			}
			$onBlocks = isset($c["onBlocks"]) ? self::blockSet(self::arr($c, "onBlocks")) : null;
			$conditions[] = new SpawnCondition(
				identifier: self::string($c, "identifier"),
				population: self::string($c, "population"),
				onSurface: self::bool($c, "onSurface"),
				underground: self::bool($c, "underground"),
				underwater: self::bool($c, "underwater"),
				lava: self::bool($c, "lava"),
				weight: self::int($c, "weight"),
				herds: $herds,
				brightnessMin: self::optInt($c, "brightnessMin"),
				brightnessMax: self::optInt($c, "brightnessMax"),
				adjustForWeather: self::bool($c, "adjustForWeather", false),
				difficultyMin: self::optInt($c, "difficultyMin") ?? 0,
				difficultyMax: self::optInt($c, "difficultyMax") ?? 3,
				heightMin: self::optInt($c, "heightMin"),
				heightMax: self::optInt($c, "heightMax"),
				distanceMin: self::optInt($c, "distanceMin"),
				distanceMax: self::optInt($c, "distanceMax"),
				densitySurface: self::optInt($c, "densitySurface"),
				densityUnderground: self::optInt($c, "densityUnderground"),
				biomeFilter: $c["biomeFilter"] ?? null,
				onBlocks: $onBlocks,
				preventedBlocks: self::blockSet(self::arr($c, "preventedBlocks", [])),
				permuteTypes: $permuteTypes,
				spawnEvent: self::optString($c, "spawnEvent"),
				disallowBubble: self::bool($c, "disallowBubble", false),
				timed: self::bool($c, "timed", false)
			);
		}
		return new SpawnRules($conditions, $populations, "Mojang/bedrock-samples " . self::TAG . " (bundled)");
	}

	/**
	 * @param mixed[] $data
	 * @param mixed[] $default
	 * @return mixed[]
	 */
	private static function arr(array $data, string $key, ?array $default = null) : array{
		$value = $data[$key] ?? $default;
		if(!is_array($value)){
			throw new \InvalidArgumentException("\"$key\" must be an array");
		}
		return $value;
	}

	/**
	 * @param mixed[] $blocks
	 * @return true[]
	 * @phpstan-return array<string, true>
	 */
	private static function blockSet(array $blocks) : array{
		$result = [];
		foreach(Utils::promoteKeys($blocks) as $name => $flag){
			if(!is_string($name) || $flag !== true){
				throw new \InvalidArgumentException("Invalid block set");
			}
			$result[$name] = true;
		}
		return $result;
	}

	/** @param mixed[] $data */
	private static function string(array $data, string $key) : string{
		$value = $data[$key] ?? null;
		if(!is_string($value)){
			throw new \InvalidArgumentException("\"$key\" must be a string");
		}
		return $value;
	}

	/** @param mixed[] $data */
	private static function optString(array $data, string $key) : ?string{
		return isset($data[$key]) ? self::string($data, $key) : null;
	}

	/** @param mixed[] $data */
	private static function int(array $data, string $key) : int{
		$value = $data[$key] ?? null;
		if(!is_int($value)){
			throw new \InvalidArgumentException("\"$key\" must be an integer");
		}
		return $value;
	}

	/** @param mixed[] $data */
	private static function optInt(array $data, string $key) : ?int{
		return isset($data[$key]) ? self::int($data, $key) : null;
	}

	/** @param mixed[] $data */
	private static function bool(array $data, string $key, ?bool $default = null) : bool{
		$value = $data[$key] ?? $default;
		if(!is_bool($value)){
			throw new \InvalidArgumentException("\"$key\" must be a boolean");
		}
		return $value;
	}

	/**
	 * @internal for tests
	 */
	public static function reset() : void{
		self::$rules = null;
		self::$loaded = false;
	}
}
