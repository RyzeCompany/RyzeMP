declare(strict_types=1);

namespace pocketmine\world\sound;

use pocketmine\math\Vector3;
use pocketmine\network\mcpe\protocol\LevelEventPacket;
use pocketmine\network\mcpe\protocol\types\LevelEvent;

/**
 * Click played by a dispenser or dropper with nothing to dispense (LevelEvent 1001, pitch 1.2 per the Minecraft Wiki
 * "Dispenser" sounds table).
 */
class ClickFailSound implements Sound{
	public function __construct(private float $pitch = 1.2){}

	public function getPitch() : float{
		return $this->pitch;
	}

	public function encode(Vector3 $pos) : array{
		return [LevelEventPacket::create(LevelEvent::SOUND_CLICK_FAIL, (int) ($this->pitch * 1000), $pos)];
	}
}
