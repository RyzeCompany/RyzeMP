namespace pocketmine\world\raid;

enum RaidStatus : string{
	/** Waves are coming. */
	case ONGOING = "ongoing";
	/** The last wave was defeated. */
	case VICTORY = "victory";
	/** The village stopped being a village (beds destroyed, villagers killed). */
	case LOSS = "loss";
	/** The raid lasted too long (Bedrock: 48000 ticks) and was called off. */
	case EXPIRED = "expired";
}
