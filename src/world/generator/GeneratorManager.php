declare(strict_types=1);

namespace pocketmine\world\generator;

use pocketmine\block\utils\VanillaTreeGrower;
use pocketmine\utils\SingletonTrait;
use pocketmine\utils\Utils;
use pocketmine\world\dimension\Dimension;
use pocketmine\world\generator\end\TheEnd;
use pocketmine\world\generator\hell\Nether;
use pocketmine\world\generator\normal\Normal;
use pocketmine\world\generator\vanilla\VanillaEndGenerator;
use pocketmine\world\generator\vanilla\VanillaGenerator;
use pocketmine\world\generator\vanilla\VanillaNetherGenerator;
use function array_keys;
use function strtolower;

final class GeneratorManager{
	/**
	 * Built-in generators that $overwrite in {@link GeneratorManager::addGenerator()} can't replace: worlds made with
	 * them must keep generating the same terrain whatever plugins are installed.
	 */
	private const PROTECTED_GENERATORS = [
		"vanilla" => true,
		"vanilla_nether" => true,
		"vanilla_end" => true,
	];
	use SingletonTrait;

	/**
	 * @var GeneratorManagerEntry[] name => classname mapping
	 * @phpstan-var array<string, GeneratorManagerEntry>
	 */
	private array $list = [];
	/**
	 * Generators of the linked Nether and End worlds of a world, by the world's generator name and dimension.
	 * @var string[][]
	 * @phpstan-var array<string, array<string, string>>
	 */
	private array $dimensionGenerators = [];

	public function __construct(){
		$this->addGenerator(Flat::class, "flat", function(string $preset) : ?InvalidGeneratorOptionsException{
			if($preset === ""){
				return null;
			}
			try{
				FlatGeneratorOptions::parsePreset($preset);
				return null;
			}catch(InvalidGeneratorOptionsException $e){
				return $e;
			}
		}, fast: true);
		$this->addGenerator(Normal::class, "normal", fn() => null);
		$this->addAlias("normal", "default");
		$vanillaValidator = function(string $preset) : ?InvalidGeneratorOptionsException{
			$error = VanillaGenerator::validatePreset($preset);
			if($error === null){
				//runs on the main thread before the world's chunks are generated by the workers
				VanillaGenerator::prepareNativeBackend();
				//the trees, huge fungi and huge mushrooms that blocks grow in vanilla worlds
				VanillaTreeGrower::prepare(VanillaGenerator::dataDirectory(VanillaGenerator::parseOptions($preset)));
			}
			return $error;
		};
		$this->addGenerator(VanillaGenerator::class, "vanilla", $vanillaValidator);
		$this->addGenerator(VanillaNetherGenerator::class, "vanilla_nether", $vanillaValidator, dimension: Dimension::NETHER);
		$this->addGenerator(VanillaEndGenerator::class, "vanilla_end", $vanillaValidator, dimension: Dimension::END);
		$this->setDimensionGenerator("vanilla", Dimension::NETHER, "vanilla_nether");
		$this->setDimensionGenerator("vanilla", Dimension::END, "vanilla_end");
		$this->addGenerator(Nether::class, "nether", fn() => null, dimension: Dimension::NETHER);
		$this->addAlias("nether", "hell");
		$this->addGenerator(TheEnd::class, "the_end", fn() => null, dimension: Dimension::END);
		$this->addAlias("the_end", "end");
	}

	/**
	 * @param string         $class           Fully qualified name of class that extends \pocketmine\world\generator\Generator
	 * @param string         $name            Alias for this generator type that can be written in configs
	 * @param \Closure       $presetValidator Callback to validate generator options for new worlds
	 * @param bool           $overwrite       Whether to force overwriting any existing registered generator with the same name
	 *                                        (the built-in vanilla, vanilla_nether and vanilla_end generators are never
	 *                                        overwritten: the registration is ignored with a warning)
	 * @param bool           $fast            Whether this generator is fast enough to run without async tasks
	 * @param Dimension|null $dimension       Dimension of the worlds it generates (null = Overworld terrain); used when a
	 *                                        world's configuration doesn't set a dimension
	 *
	 * @phpstan-param \Closure(string) : ?InvalidGeneratorOptionsException $presetValidator
	 *
	 * @phpstan-param class-string<Generator> $class
	 *
	 * @throws \InvalidArgumentException
	 */
	public function addGenerator(string $class, string $name, \Closure $presetValidator, bool $overwrite = false, bool $fast = false, ?Dimension $dimension = null) : void{
		Utils::testValidInstance($class, Generator::class);

		$name = strtolower($name);
		if(isset($this->list[$name])){
			if(!$overwrite){
				throw new \InvalidArgumentException("Alias \"$name\" is already assigned");
			}
			if(isset(self::PROTECTED_GENERATORS[$name])){
				//e.g. MultiWorld registers Muqsit's old VanillaGenerator as "vanilla_nether" with $overwrite: the Nether
				//of our vanilla worlds would get new chunks from a different generator
				\GlobalLogger::get()->warning("Ignored the registration of generator \"$name\" ($class): the built-in vanilla generators can't be replaced");
				return;
			}
		}

		$this->list[$name] = new GeneratorManagerEntry($class, $presetValidator, $fast, $dimension);
	}

	/**
	 * Aliases an already-registered generator name to another name. Useful if you want to map a generator name to an
	 * existing generator without having to replicate the parameters.
	 */
	public function addAlias(string $name, string $alias) : void{
		$name = strtolower($name);
		$alias = strtolower($alias);
		if(!isset($this->list[$name])){
			throw new \InvalidArgumentException("Alias \"$name\" is not assigned");
		}
		if(isset($this->list[$alias])){
			throw new \InvalidArgumentException("Alias \"$alias\" is already assigned");
		}
		$this->list[$alias] = $this->list[$name];
	}

	/**
	 * Sets the generator used to create the linked world of the given dimension (e.g. "world_nether") of worlds made
	 * with the generator $generatorName. Without one, the dimension's default generator is used (see
	 * Dimension::getDefaultGeneratorName()). The linked world gets the same generator options as the world.
	 *
	 * @throws \InvalidArgumentException if either generator is not registered
	 */
	public function setDimensionGenerator(string $generatorName, Dimension $dimension, string $dimensionGeneratorName) : void{
		$generatorName = strtolower($generatorName);
		$dimensionGeneratorName = strtolower($dimensionGeneratorName);
		if(!isset($this->list[$generatorName])){
			throw new \InvalidArgumentException("Generator \"$generatorName\" is not registered");
		}
		if(!isset($this->list[$dimensionGeneratorName])){
			throw new \InvalidArgumentException("Generator \"$dimensionGeneratorName\" is not registered");
		}
		$this->dimensionGenerators[$generatorName][$dimension->name] = $dimensionGeneratorName;
	}

	/**
	 * Returns the name of the generator for the linked world of the given dimension of worlds made with
	 * $generatorName, or null if there is none (the dimension's default generator is used then).
	 */
	public function getDimensionGenerator(string $generatorName, Dimension $dimension) : ?string{
		return $this->dimensionGenerators[strtolower($generatorName)][$dimension->name] ?? null;
	}

	/**
	 * Returns a list of names for registered generators.
	 *
	 * @return string[]
	 */
	public function getGeneratorList() : array{
		return array_keys($this->list);
	}

	/**
	 * Returns the generator entry of a registered Generator matching the given name, or null if not found.
	 */
	public function getGenerator(string $name) : ?GeneratorManagerEntry{
		return $this->list[strtolower($name)] ?? null;
	}

	/**
	 * Returns the registered name of the given Generator class.
	 *
	 * @param string $class Fully qualified name of class that extends \pocketmine\world\generator\Generator
	 * @phpstan-param class-string<Generator> $class
	 *
	 * @throws \InvalidArgumentException if the class type cannot be matched to a known alias
	 */
	public function getGeneratorName(string $class) : string{
		Utils::testValidInstance($class, Generator::class);
		foreach(Utils::stringifyKeys($this->list) as $name => $c){
			if($c->getGeneratorClass() === $class){
				return $name;
			}
		}

		throw new \InvalidArgumentException("Generator class $class is not registered");
	}
}
