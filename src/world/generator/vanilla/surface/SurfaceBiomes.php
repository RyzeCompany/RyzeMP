declare(strict_types=1);

namespace pocketmine\world\generator\vanilla\surface;

use pocketmine\world\generator\vanilla\biome\ClimateBiomeTree;
use pocketmine\world\generator\vanilla\compiler\CompiledKernel;
use pocketmine\world\generator\vanilla\math\Int64;
use pocketmine\world\generator\vanilla\NoiseRouter;
use pocketmine\world\generator\vanilla\TerrainChunk;
use pocketmine\world\World;
use function array_key_first;
use function count;
use function hash;
use function pack;
use function substr;
use function unpack;
use const INF;
use const PHP_INT_MIN;

/**
 * Block-level biome lookups during the surface stage, like vanilla's BiomeManager: the biome of a block is the one of
 * the 4x4x4 cell corner closest to it after a seed-dependent "fiddle" of each corner (the fuzzy zoom), so biome
 * borders are not aligned to the cell grid. Cells of the neighbouring chunks are computed from the climate noise.
 */
final class SurfaceBiomes{
	private const RECENT_CHUNKS = 64;
	private const LCG_MULTIPLIER = 6364136223846793005;
	private const LCG_INCREMENT = 1442695040888963407;

	private readonly int $zoomSeed;
	private readonly int $minQuart;
	private readonly int $quartsY;

	private int $baseQuartX = 0;
	private int $baseQuartZ = 0;
	/**
	 * Cell biomes of recently decorated chunks (TerrainChunk::$biomes by chunk hash): neighbours are usually
	 * generated by the same worker (population generates the 3x3 chunks around), so most cells around a chunk do
	 * not need to be computed again.
	 * @var int[][]
	 * @phpstan-var array<int, array<int, int>>
	 */
	private array $recentChunks = [];
	private int $lastLocalX = -1;
	private int $lastLocalZ = -1;
	private int $lastParentY = PHP_INT_MIN;
	private int $lastUniform = -1;
	/**
	 * Biome per cell around the chunk (local cell x/z -1..4), index ((lqx + 1) * 6 + lqz + 1) * quartsY + qy; -1 = not computed.
	 * @var int[]
	 * @phpstan-var array<int, int>
	 */
	private array $cells = [];
	/**
	 * Fiddle offsets per corner, 3 floats per corner at index (((lqx + 1) * 6 + lqz + 1) * (quartsY + 2) + cy - minQuart + 1) * 3.
	 * @var float[]
	 * @phpstan-var array<int, float>
	 */
	private array $fiddles = [];
	/**
	 * Biome of a zoom cell whose 8 corners share it (-1 = mixed), per parent cell.
	 * @var int[]
	 * @phpstan-var array<int, int>
	 */
	private array $uniform = [];

	/**
	 * @param CompiledKernel|null $kernel faster climate sampling for the cells of neighbouring chunks (same values)
	 */
	public function __construct(
		private readonly NoiseRouter $router,
		private readonly ClimateBiomeTree $tree,
		int $seed,
		private readonly ?CompiledKernel $kernel = null
	){
		$this->zoomSeed = self::obfuscateSeed($seed);
		$this->minQuart = $router->minY >> 2;
		$this->quartsY = $router->height >> 2;
	}

	/** BiomeManager.obfuscateSeed(): first 8 bytes (little endian) of the SHA-256 of the seed (little endian). */
	public static function obfuscateSeed(int $seed) : int{
		$unpacked = unpack("P", substr(hash("sha256", pack("P", $seed), true), 0, 8));
		if($unpacked === false){
			throw new \LogicException("unpack() failed");
		}
		/** @var int $value */
		$value = $unpacked[1];
		return $value;
	}

	public function beginChunk(TerrainChunk $terrain) : void{
		$this->baseQuartX = $terrain->chunkX << 2;
		$this->baseQuartZ = $terrain->chunkZ << 2;
		$this->cells = [];
		$this->fiddles = [];
		$this->uniform = [];
		$this->lastLocalX = -1;
		$quartsY = $this->quartsY;
		$biomes = $terrain->biomes;
		unset($this->recentChunks[World::chunkHash($terrain->chunkX, $terrain->chunkZ)]);
		$this->recentChunks[World::chunkHash($terrain->chunkX, $terrain->chunkZ)] = $biomes;
		if(count($this->recentChunks) > self::RECENT_CHUNKS){
			unset($this->recentChunks[array_key_first($this->recentChunks)]);
		}
		for($qx = 0; $qx < 4; ++$qx){
			for($qz = 0; $qz < 4; ++$qz){
				$src = (($qx << 2) | $qz) * $quartsY;
				$dst = (($qx + 1) * 6 + $qz + 1) * $quartsY;
				for($qy = 0; $qy < $quartsY; ++$qy){
					$this->cells[$dst + $qy] = $biomes[$src + $qy];
				}
			}
		}
	}

	/**
	 * Biome index (ClimateBiomeTree names) at a block; $localX/$localZ are 0-15 inside the current chunk.
	 */
	public function getBiome(int $localX, int $y, int $localZ) : int{
		$absX = $localX - 2;
		$absY = $y - 2;
		$absZ = $localZ - 2;
		$px = $absX >> 2;
		$py = $absY >> 2;
		$pz = $absZ >> 2;
		if($py === $this->lastParentY && $localX === $this->lastLocalX && $localZ === $this->lastLocalZ){
			return $this->lastUniform;
		}
		$parent = (($px + 1) * 6 + $pz + 1) * ($this->quartsY + 1) + $py - $this->minQuart + 1;
		if(!isset($this->uniform[$parent])){
			$this->computeUniform($parent, $px, $py, $pz);
		}
		$uniform = $this->uniform[$parent];
		if($uniform >= 0){
			$this->lastLocalX = $localX;
			$this->lastLocalZ = $localZ;
			$this->lastParentY = $absY >> 2;
			$this->lastUniform = $uniform;
			return $uniform;
		}
		//recomputed on purpose: PHP 8.4's function JIT lost these values across the computeUniform() call
		$px = $absX >> 2;
		$py = $absY >> 2;
		$pz = $absZ >> 2;

		$fx = ($absX & 3) / 4.0;
		$fy = ($absY & 3) / 4.0;
		$fz = ($absZ & 3) / 4.0;
		$best = 0;
		$bestDistance = INF;
		for($i = 0; $i < 8; ++$i){
			$xEven = ($i & 4) === 0;
			$yEven = ($i & 2) === 0;
			$zEven = ($i & 1) === 0;
			$cx = $xEven ? $px : $px + 1;
			$cy = $yEven ? $py : $py + 1;
			$cz = $zEven ? $pz : $pz + 1;
			$o = $this->fiddleIndex($cx, $cy, $cz);
			$dx = ($xEven ? $fx : $fx - 1.0) + $this->fiddles[$o];
			$dy = ($yEven ? $fy : $fy - 1.0) + $this->fiddles[$o + 1];
			$dz = ($zEven ? $fz : $fz - 1.0) + $this->fiddles[$o + 2];
			$distance = $dz * $dz + $dy * $dy + $dx * $dx;
			if($bestDistance > $distance){
				$best = $i;
				$bestDistance = $distance;
			}
		}
		return $this->cell(
			($best & 4) === 0 ? $px : $px + 1,
			($best & 2) === 0 ? $py : $py + 1,
			($best & 1) === 0 ? $pz : $pz + 1
		);
	}

	private function computeUniform(int $parent, int $px, int $py, int $pz) : int{
		$first = $this->cell($px, $py, $pz);
		for($i = 1; $i < 8; ++$i){
			if($this->cell(($i & 4) === 0 ? $px : $px + 1, ($i & 2) === 0 ? $py : $py + 1, ($i & 1) === 0 ? $pz : $pz + 1) !== $first){
				return $this->uniform[$parent] = -1;
			}
		}
		return $this->uniform[$parent] = $first;
	}

	/**
	 * Biome of a cell (local cell x/z -1..4, absolute cell y clamped to the world like ChunkAccess.getNoiseBiome()).
	 */
	private function cell(int $lqx, int $qy, int $lqz) : int{
		$iy = $qy - $this->minQuart;
		if($iy < 0){
			$iy = 0;
		}elseif($iy >= $this->quartsY){
			$iy = $this->quartsY - 1;
		}
		$column = ($lqx + 1) * 6 + $lqz + 1;
		$index = $column * $this->quartsY + $iy;
		if(isset($this->cells[$index])){
			return $this->cells[$index];
		}
		$neighbour = $this->recentChunks[World::chunkHash(($this->baseQuartX + $lqx) >> 2, ($this->baseQuartZ + $lqz) >> 2)] ?? null;
		if($neighbour !== null){
			return $this->cells[$index] = $neighbour[(((($lqx & 3) << 2) | ($lqz & 3)) * $this->quartsY) + $iy];
		}
		//whole column bottom to top, like the terrain stage: consecutive searches start from the previous result
		$climate = $this->sampleClimate($lqx, $lqz);
		$r = $this->router;
		$k = $this->kernel;
		$x = (float) (($this->baseQuartX + $lqx) << 2);
		$z = (float) (($this->baseQuartZ + $lqz) << 2);
		$base = $column * $this->quartsY;
		for($cellY = 0; $cellY < $this->quartsY; ++$cellY){
			$y = (float) (($this->minQuart + $cellY) << 2);
			$depth = ClimateBiomeTree::quantize($k !== null ? $k->depth($x, $y, $z) : $r->depth->compute($x, $y, $z));
			$this->cells[$base + $cellY] = $this->tree->search($climate[0], $climate[1], $climate[2], $climate[3], $depth, $climate[4]);
		}
		return $this->cells[$index];
	}

	/**
	 * @phpstan-return array{int, int, int, int, int}
	 */
	private function sampleClimate(int $lqx, int $lqz) : array{
		$r = $this->router;
		$x = (float) (($this->baseQuartX + $lqx) << 2);
		$z = (float) (($this->baseQuartZ + $lqz) << 2);
		$k = $this->kernel;
		if($k !== null){
			return [
				ClimateBiomeTree::quantize($k->temperature($x, 0.0, $z)),
				ClimateBiomeTree::quantize($k->vegetation($x, 0.0, $z)),
				ClimateBiomeTree::quantize($k->continents($x, 0.0, $z)),
				ClimateBiomeTree::quantize($k->erosion($x, 0.0, $z)),
				ClimateBiomeTree::quantize($k->ridges($x, 0.0, $z)),
			];
		}
		return [
			ClimateBiomeTree::quantize($r->temperature->compute($x, 0.0, $z)),
			ClimateBiomeTree::quantize($r->vegetation->compute($x, 0.0, $z)),
			ClimateBiomeTree::quantize($r->continents->compute($x, 0.0, $z)),
			ClimateBiomeTree::quantize($r->erosion->compute($x, 0.0, $z)),
			ClimateBiomeTree::quantize($r->ridges->compute($x, 0.0, $z)),
		];
	}

	private function fiddleIndex(int $lqx, int $cy, int $lqz) : int{
		$index = ((($lqx + 1) * 6 + $lqz + 1) * ($this->quartsY + 2) + $cy - $this->minQuart + 1) * 3;
		if(!isset($this->fiddles[$index])){
			$seed = $this->zoomSeed;
			$x = $this->baseQuartX + $lqx;
			$z = $this->baseQuartZ + $lqz;
			$r = self::lcg($seed, $x);
			$r = self::lcg($r, $cy);
			$r = self::lcg($r, $z);
			$r = self::lcg($r, $x);
			$r = self::lcg($r, $cy);
			$r = self::lcg($r, $z);
			$this->fiddles[$index] = self::fiddle($r);
			$r = self::lcg($r, $seed);
			$this->fiddles[$index + 1] = self::fiddle($r);
			$r = self::lcg($r, $seed);
			$this->fiddles[$index + 2] = self::fiddle($r);
		}
		return $index;
	}

	/** LinearCongruentialGenerator.next() */
	private static function lcg(int $value, int $add) : int{
		return Int64::add(Int64::mul($value, Int64::add(Int64::mul($value, self::LCG_MULTIPLIER), self::LCG_INCREMENT)), $add);
	}

	private static function fiddle(int $value) : float{
		return ((($value >> 24) & 1023) / 1024.0 - 0.5) * 0.9;
	}
}
