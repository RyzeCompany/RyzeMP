declare(strict_types=1);

namespace pocketmine\world\map;

use pocketmine\data\bedrock\block\BlockStateNames;
use pocketmine\data\bedrock\block\BlockStateSerializeException;
use pocketmine\data\bedrock\block\BlockStateStringValues;
use pocketmine\nbt\tag\StringTag;
use pocketmine\utils\Filesystem;
use pocketmine\utils\SingletonTrait;
use pocketmine\utils\Utils;
use pocketmine\world\format\io\GlobalBlockStateHandlers;
use Symfony\Component\Filesystem\Path;
use function hexdec;
use function is_array;
use function is_string;
use function json_decode;
use function preg_match;
use const JSON_THROW_ON_ERROR;

/**
 * Base map colour of each block, as vanilla Bedrock reports it (resources/block_map_colors.json, generated by
 * tools/generate-block-map-colors.php from a Bedrock Dedicated Server block state dump).
 *
 * Colours are 0xRRGGBB ints; NONE means the block doesn't show on maps (air, glass, ...) so the map looks through it.
 */
final class BlockMapColors{
	use SingletonTrait;

	public const NONE = -1;
	/** Used for blocks missing from the table, so that new blocks still show up */
	public const FALLBACK = 0x707070;

	public const WATER = 0x4040ff;

	/** Brightness multipliers used for height shading (out of 255), as in vanilla */
	public const SHADE_LOW = 180;
	public const SHADE_NORMAL = 220;
	public const SHADE_HIGH = 255;
	public const SHADE_LOWEST = 135;

	/**
	 * @var int[]
	 * @phpstan-var array<string, int>
	 */
	private array $colors = [];
	/**
	 * Colours of the cut face of logs (pillar_axis=y), seen from above
	 * @var int[]
	 * @phpstan-var array<string, int>
	 */
	private array $pillarAxisYColors = [];

	/**
	 * Cache of colours by block state ID
	 * @var int[]
	 * @phpstan-var array<int, int>
	 */
	private array $stateColors = [];

	public function __construct(?string $path = null){
		$data = json_decode(Filesystem::fileGetContents($path ?? Path::join(\pocketmine\RESOURCE_PATH, "block_map_colors.json")), true, 4, JSON_THROW_ON_ERROR);
		if(!is_array($data) || !is_array($data["colors"] ?? null) || !is_array($data["pillar_axis_y"] ?? null)){
			throw new \InvalidArgumentException("Invalid block map colour table");
		}
		$this->colors = self::parseColors($data["colors"]);
		$this->pillarAxisYColors = self::parseColors($data["pillar_axis_y"]);
	}

	/**
	 * @param mixed[] $colors
	 * @phpstan-return array<string, int>
	 */
	private static function parseColors(array $colors) : array{
		$result = [];
		foreach(Utils::promoteKeys($colors) as $name => $color){
			if($color === "none"){
				$result[(string) $name] = self::NONE;
				continue;
			}
			if(!is_string($color) || preg_match('/^[0-9a-f]{6}$/', $color) !== 1){
				throw new \InvalidArgumentException("Invalid map colour for $name");
			}
			$result[(string) $name] = (int) hexdec($color);
		}
		return $result;
	}

	/**
	 * Returns the base map colour (0xRRGGBB) of the block with the given vanilla ID, or NONE if it doesn't show on
	 * maps. Blocks missing from the table get FALLBACK.
	 */
	public function getColorByName(string $name, ?string $pillarAxis = null) : int{
		if($pillarAxis === BlockStateStringValues::PILLAR_AXIS_Y && isset($this->pillarAxisYColors[$name])){
			return $this->pillarAxisYColors[$name];
		}
		return $this->colors[$name] ?? self::FALLBACK;
	}

	/**
	 * Returns whether the table has a colour (or explicitly no colour) for the given block.
	 */
	public function isKnown(string $name) : bool{
		return isset($this->colors[$name]) || isset($this->pillarAxisYColors[$name]);
	}

	/**
	 * Returns the base map colour (0xRRGGBB) of the given block state, or NONE if it doesn't show on maps.
	 */
	public function getColor(int $stateId) : int{
		if(isset($this->stateColors[$stateId])){
			return $this->stateColors[$stateId];
		}
		try{
			$data = GlobalBlockStateHandlers::getSerializer()->serialize($stateId);
			$axis = $data->getState(BlockStateNames::PILLAR_AXIS);
			$color = $this->getColorByName($data->getName(), $axis instanceof StringTag ? $axis->getValue() : null);
		}catch(BlockStateSerializeException){
			$color = self::FALLBACK;
		}
		return $this->stateColors[$stateId] = $color;
	}

	/**
	 * Applies a shading brightness (SHADE_*) to a base colour.
	 */
	public static function shade(int $color, int $brightness) : int{
		$r = (($color >> 16) & 0xff) * $brightness / 255;
		$g = (($color >> 8) & 0xff) * $brightness / 255;
		$b = ($color & 0xff) * $brightness / 255;
		return ((int) $r << 16) | ((int) $g << 8) | (int) $b;
	}
}
