declare(strict_types=1);

namespace pocketmine\world\particle;

use pocketmine\math\Vector3;
use pocketmine\network\mcpe\protocol\LevelEventPacket;
use pocketmine\network\mcpe\protocol\types\LevelEvent;

/**
 * A vault turning off when no player it can reward is near any more (smoke and sound). Sent at the block position.
 */
class VaultDeactivateParticle implements Particle{

	public function __construct(
		private bool $ominous = false
	){}

	public function encode(Vector3 $pos) : array{
		return [LevelEventPacket::create(LevelEvent::ANIMATION_VAULT_DEACTIVATE, $this->ominous ? 1 : 0, $pos)];
	}
}
