/**
 * Minimal reader of Java Edition (big endian) NBT into PHP values: compounds and lists are arrays, long arrays are
 * lists of ints (PocketMine's NBT library has no long array tag).
 */
final class JavaNbt{
	private int $offset = 0;

	private function __construct(private string $buffer){}

	/**
	 * @phpstan-return array<string, mixed>
	 */
	public static function readRoot(string $buffer) : array{
		$reader = new self($buffer);
		if($reader->byte() !== 10){
			throw new \RuntimeException("Root tag is not a compound");
		}
		$reader->string();
		$value = $reader->payload(10);
		return is_array($value) ? $value : [];
	}

	private function bytes(int $length) : string{
		$value = substr($this->buffer, $this->offset, $length);
		$this->offset += $length;
		return $value;
	}

	private function byte() : int{
		return ord($this->bytes(1));
	}

	private function int() : int{
		$value = Utils::assumeNotFalse(unpack("N", $this->bytes(4)))[1];
		return is_int($value) ? ($value >= 0x80000000 ? $value - 0x100000000 : $value) : 0;
	}

	private function string() : string{
		$length = Utils::assumeNotFalse(unpack("n", $this->bytes(2)))[1];
		return $this->bytes(is_int($length) ? $length : 0);
	}

	private function payload(int $type) : mixed{
		switch($type){
			case 1: return $this->byte();
			case 2: $v = Utils::assumeNotFalse(unpack("n", $this->bytes(2)))[1]; return is_int($v) ? $v : 0;
			case 3: return $this->int();
			case 4: $v = Utils::assumeNotFalse(unpack("J", $this->bytes(8)))[1]; return is_int($v) ? $v : 0;
			case 5: $this->offset += 4; return 0.0;
			case 6: $this->offset += 8; return 0.0;
			case 7: return $this->bytes($this->int());
			case 8: return $this->string();
			case 9:
				$elementType = $this->byte();
				$count = $this->int();
				$list = [];
				for($i = 0; $i < $count; ++$i){
					$list[] = $this->payload($elementType);
				}
				return $list;
			case 10:
				$compound = [];
				while(($childType = $this->byte()) !== 0){
					$name = $this->string();
					$compound[$name] = $this->payload($childType);
				}
				return $compound;
			case 11:
				$count = $this->int();
				$list = [];
				for($i = 0; $i < $count; ++$i){
					$list[] = $this->int();
				}
				return $list;
			case 12:
				$count = $this->int();
				$list = [];
				for($i = 0; $i < $count; ++$i){
					$v = Utils::assumeNotFalse(unpack("J", $this->bytes(8)))[1];
					$list[] = is_int($v) ? $v : 0;
				}
				return $list;
			default:
				throw new \RuntimeException("Unknown NBT tag type $type");
		}
	}
}

/**
 * Reads blocks of a Java Edition world (region/*.mca, 1.18+ "sections" format).
 */
final class JavaRegionReader{
	/** @phpstan-var array<string, array<int, list<string>>|null> "x:z" => section y => 4096 block state strings (null: missing / not full) */
	private array $chunks = [];

	public function __construct(private string $regionDir){}

	/**
	 * @phpstan-return array<string, mixed>|null
	 */
	public function readChunkNbt(int $chunkX, int $chunkZ) : ?array{
		$file = sprintf("%s/r.%d.%d.mca", $this->regionDir, $chunkX >> 5, $chunkZ >> 5);
		if(!is_file($file)){
			return null;
		}
		$handle = fopen($file, "rb");
		if($handle === false){
			return null;
		}
		try{
			fseek($handle, 4 * (($chunkX & 31) + ($chunkZ & 31) * 32));
			$header = fread($handle, 4);
			if($header === false || strlen($header) < 4){
				return null;
			}
			$location = Utils::assumeNotFalse(unpack("N", $header))[1];
			if(!is_int($location) || $location === 0){
				return null;
			}
			fseek($handle, ($location >> 8) * 4096);
			$head = fread($handle, 5);
			if($head === false || strlen($head) < 5){
				return null;
			}
			$length = Utils::assumeNotFalse(unpack("N", $head))[1];
			if(!is_int($length) || $length < 1){
				return null;
			}
			$compression = ord($head[4]);
			$payload = $length > 1 ? fread($handle, $length - 1) : "";
			if($payload === false){
				return null;
			}
		}finally{
			fclose($handle);
		}
		$raw = match($compression){
			1 => gzdecode($payload),
			2 => zlib_decode($payload),
			3 => $payload,
			default => throw new \RuntimeException("Unsupported chunk compression $compression (use deflate in server.properties)")
		};
		if($raw === false){
			throw new \RuntimeException("Corrupted chunk $chunkX $chunkZ");
		}
		return JavaNbt::readRoot($raw);
	}

	/**
	 * @phpstan-return array<int, list<string>>|null
	 */
	private function loadChunk(int $chunkX, int $chunkZ) : ?array{
		$key = "$chunkX:$chunkZ";
		if(array_key_exists($key, $this->chunks)){
			return $this->chunks[$key];
		}
		$nbt = $this->readChunkNbt($chunkX, $chunkZ);
		if($nbt === null || ($nbt["Status"] ?? "") !== "minecraft:full"){
			return $this->chunks[$key] = null;
		}
		$sections = [];
		foreach(is_array($nbt["sections"] ?? null) ? $nbt["sections"] : [] as $section){
			if(!is_array($section) || !is_array($section["block_states"] ?? null) || !is_int($section["Y"] ?? null)){
				continue;
			}
			$states = $section["block_states"];
			$palette = [];
			foreach(is_array($states["palette"] ?? null) ? $states["palette"] : [] as $entry){
				//1.21.5+: a state without properties may be stored as its name, wrapped as {"": name} in mixed lists
				if(is_array($entry) && is_string($entry[""] ?? null)){
					$entry = $entry[""];
				}
				if(is_string($entry)){
					$palette[] = $entry;
					continue;
				}
				//{Name, Properties} (1.18) or {id, properties} (26.x, default property values omitted)
				$blockName = is_array($entry) ? ($entry["Name"] ?? $entry["id"] ?? null) : null;
				if(!is_array($entry) || !is_string($blockName)){
					$palette[] = "minecraft:air";
					continue;
				}
				$properties = [];
				$values = $entry["Properties"] ?? $entry["properties"] ?? null;
				foreach(is_array($values) ? Utils::promoteKeys($values) : [] as $name => $value){
					if(is_string($value)){
						$properties[$name] = $name . "=" . $value;
					}
				}
				ksort($properties);
				$palette[] = $blockName . (count($properties) > 0 ? "[" . implode(",", $properties) . "]" : "");
			}
			$blocks = [];
			$longs = $states["data"] ?? null;
			if(count($palette) === 1 || !is_array($longs)){
				for($i = 0; $i < 4096; ++$i){
					$blocks[] = $palette[0] ?? "minecraft:air";
				}
			}else{
				$bits = max(4, strlen(decbin(count($palette) - 1)));
				$perLong = intdiv(64, $bits);
				$mask = (1 << $bits) - 1;
				for($i = 0; $i < 4096; ++$i){
					$long = $longs[intdiv($i, $perLong)] ?? 0;
					$blocks[] = $palette[((is_int($long) ? $long : 0) >> (($i % $perLong) * $bits)) & $mask] ?? "minecraft:air";
				}
			}
			$sections[$section["Y"] >= 128 ? $section["Y"] - 256 : $section["Y"]] = $blocks;
		}
		return $this->chunks[$key] = $sections;
	}

	public function isFull(int $chunkX, int $chunkZ) : bool{
		return $this->loadChunk($chunkX, $chunkZ) !== null;
	}

	public function getBlock(int $x, int $y, int $z) : string{
		$sections = $this->loadChunk($x >> 4, $z >> 4);
		$section = $sections[$y >> 4] ?? null;
		return $section === null ? "minecraft:air" : $section[(($y & 15) << 8) | (($z & 15) << 4) | ($x & 15)];
	}
}

/** @phpstan-var array<string, string> $opts */
$opts = getopt("", ["data:", "java-world:", "seed:", "structure:", "near:", "box:", "dimension:", "backend:", "margin:", "samples:", "diff-out:"]);
$data = $opts["data"] ?? null;
$javaWorld = $opts["java-world"] ?? null;
if(!is_string($data) || !is_string($javaWorld)){
	fwrite(STDERR, "Usage: see the header of this file" . PHP_EOL);
	exit(1);
}
$seed = (int) ($opts["seed"] ?? 0);
$dimension = $opts["dimension"] ?? "overworld";
$backend = $opts["backend"] ?? "compiled";
$margin = (int) ($opts["margin"] ?? 0);
$samples = (int) ($opts["samples"] ?? 5);

$options = "data=$data;backend=$backend;structure-positions=java";
$generator = match($dimension){
	"nether" => new VanillaNetherGenerator($seed, $options),
	"end" => new VanillaEndGenerator($seed, $options),
	default => new VanillaGenerator($seed, $options)
};
[$minY, $maxY, $regionDir, $dimensionName] = match($dimension){
	"nether" => [0, 128, "$javaWorld/DIM-1/region", "the_nether"],
	"end" => [0, 256, "$javaWorld/DIM1/region", "the_end"],
	default => [-64, 320, "$javaWorld/region", "overworld"]
};
if(is_dir("$javaWorld/dimensions/minecraft/$dimensionName/region")){
	//26.x world layout
	$regionDir = "$javaWorld/dimensions/minecraft/$dimensionName/region";
}

if(isset($opts["box"])){
	$v = array_map(fn(string $s) : int => (int) $s, explode(",", $opts["box"], 7));
	if(count($v) !== 6){
		fwrite(STDERR, "--box needs 6 values" . PHP_EOL);
		exit(1);
	}
	$box = BoundingBox::fromCorners($v[0], $v[1], $v[2], $v[3], $v[4], $v[5]);
	printf("Box %s\n", $box);
}else{
	$structure = $opts["structure"] ?? null;
	$manager = $generator->getStructureManager();
	if(!is_string($structure) || $manager === null){
		fwrite(STDERR, "--structure or --box is required" . PHP_EOL);
		exit(1);
	}
	$near = array_map(fn(string $s) : int => (int) $s, explode(",", $opts["near"] ?? "0,0", 3));
	$found = $manager->locate($structure, $near[0], $near[1] ?? 0);
	if($found === null){
		fwrite(STDERR, "No $structure found" . PHP_EOL);
		exit(1);
	}
	[$id, $startX, $startZ] = $found;
	$start = null;
	foreach($manager->getStartsAffecting($startX, $startZ) as $candidate){
		if($candidate->chunkX === $startX && $candidate->chunkZ === $startZ && $candidate->structure->id === $id){
			$start = $candidate;
		}
	}
	if($start === null){
		fwrite(STDERR, "Start of $id at chunk $startX $startZ not found" . PHP_EOL);
		exit(1);
	}
	$box = $start->getPiecesBoundingBox()->inflatedBy($margin);
	printf("%s at chunk %d %d: %d pieces, box %s\n", $id, $startX, $startZ, count($start->pieces), $box);
	$startPieces = $start->pieces;
	$startId = $id;
}
$box = new BoundingBox($box->minX, max($minY, $box->minY), $box->minZ, $box->maxX, min($maxY - 1, $box->maxY), $box->maxZ);

$java = new JavaRegionReader($regionDir);
if(isset($startPieces, $startId, $startX, $startZ)){
	//the pieces Java saved with the start (structures.starts of the start chunk): same count and boxes in order?
	$nbt = $java->readChunkNbt($startX, $startZ);
	$structures = $nbt["structures"] ?? null;
	$starts = is_array($structures) ? ($structures["starts"] ?? null) : null;
	$savedStart = is_array($starts) ? ($starts[$startId] ?? null) : null;
	$saved = is_array($savedStart) ? ($savedStart["Children"] ?? null) : null;
	if(!is_array($saved)){
		printf("Java start: not saved in chunk %d %d\n", $startX, $startZ);
	}else{
		$mismatch = 0;
		foreach(Utils::promoteKeys($saved) as $i => $child){
			$bb = [];
			if(is_array($child) && is_array($child["BB"] ?? null)){
				foreach($child["BB"] as $v){
					$bb[] = is_int($v) ? $v : 0;
				}
			}
			$ourBox = isset($startPieces[$i]) ? $startPieces[$i]->box->toArray() : [];
			if($bb !== $ourBox){
				if(++$mismatch <= 5){
					printf("  piece %d: java %s %s, ours %s\n", $i, is_array($child) && is_string($child["id"] ?? null) ? $child["id"] : "?", implode(",", $bb), implode(",", $ourBox));
				}
			}
		}
		printf("Java start: %d pieces (ours %d), %d boxes differ\n", count($saved), count($startPieces), $mismatch);
	}
}
$blocks = JavaBlocks::get($data);
$world = new SimpleChunkManager($minY, $maxY);
$minCX = $box->minX >> 4;
$maxCX = $box->maxX >> 4;
$minCZ = $box->minZ >> 4;
$maxCZ = $box->maxZ >> 4;
$t = microtime(true);
for($x = $minCX - 1; $x <= $maxCX + 1; ++$x){
	for($z = $minCZ - 1; $z <= $maxCZ + 1; ++$z){
		$world->setChunk($x, $z, new Chunk([], false));
		$generator->generateChunk($world, $x, $z);
	}
}
for($x = $minCX; $x <= $maxCX; ++$x){
	for($z = $minCZ; $z <= $maxCZ; ++$z){
		$generator->populateChunk($world, $x, $z);
	}
}
printf("Generated %d chunks in %.1f s\n", ($maxCX - $minCX + 1) * ($maxCZ - $minCZ + 1), microtime(true) - $t);

/** @phpstan-var array<string, string> $canonical Java state string => canonical string */
$canonical = [];
$canonicalJava = function(string $state) use (&$canonical, $blocks) : string{
	if(isset($canonical[$state])){
		return $canonical[$state];
	}
	try{
		$id = $blocks->parseState($state);
	}catch(\Throwable){
		return $canonical[$state] = "?" . $state;
	}
	$wet = $blocks->getProperty($id, "waterlogged") === "true";
	return $canonical[$state] = $blocks->describe($blocks->fromPm($blocks->toPm($id), $wet)) . ($wet ? "+water" : "");
};
$ours = function(int $x, int $y, int $z) use ($world, $blocks) : string{
	$chunk = $world->getChunk($x >> 4, $z >> 4);
	if($chunk === null){
		return "minecraft:air";
	}
	$subChunk = $chunk->getSubChunk($y >> 4);
	$layers = $subChunk->getBlockLayers();
	$pm = isset($layers[0]) ? $layers[0]->get($x & 15, $y & 15, $z & 15) : $blocks->pmAirState();
	$wet = isset($layers[1]) && $layers[1]->get($x & 15, $y & 15, $z & 15) === $blocks->pmWaterState();
	$state = $blocks->fromPm($pm, $wet);
	return $blocks->describe($state) . ($wet && $blocks->getProperty($state, "waterlogged") === "true" ? "+water" : "");
};

$compared = 0;
$skippedChunks = 0;
$diffs = 0;
/** @phpstan-var array<string, int> $pairs */
$pairs = [];
/** @phpstan-var array<string, list<string>> $where */
$where = [];
$lines = [];
for($cx = $minCX; $cx <= $maxCX; ++$cx){
	for($cz = $minCZ; $cz <= $maxCZ; ++$cz){
		if(!$java->isFull($cx, $cz)){
			++$skippedChunks;
			continue;
		}
		for($x = max($box->minX, $cx << 4); $x <= min($box->maxX, ($cx << 4) + 15); ++$x){
			for($z = max($box->minZ, $cz << 4); $z <= min($box->maxZ, ($cz << 4) + 15); ++$z){
				for($y = $box->minY; $y <= $box->maxY; ++$y){
					++$compared;
					$a = $canonicalJava($java->getBlock($x, $y, $z));
					$b = $ours($x, $y, $z);
					if($a !== $b){
						++$diffs;
						$pair = "$a -> $b";
						$pairs[$pair] = ($pairs[$pair] ?? 0) + 1;
						if(count($where[$pair] ?? []) < $samples){
							$where[$pair][] = "$x,$y,$z";
						}
						$lines[] = "$x $y $z java=$a ours=$b";
					}
				}
			}
		}
	}
}
printf("Compared %d blocks (%d chunks not full in the Java world): %d differ (%.2f%%)\n", $compared, $skippedChunks, $diffs, $compared > 0 ? $diffs * 100 / $compared : 0);
arsort($pairs);
$shown = 0;
foreach(Utils::stringifyKeys($pairs) as $pair => $count){
	printf("%7d  java %s   [%s]\n", $count, $pair, implode(" ", $where[$pair] ?? []));
	if(++$shown >= 60){
		break;
	}
}
if(isset($opts["diff-out"])){
	file_put_contents($opts["diff-out"], implode("\n", $lines) . "\n");
}
