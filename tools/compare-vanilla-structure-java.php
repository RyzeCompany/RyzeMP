/**
 * Compares the blocks of a structure generated by the vanilla generator (Java structure positions) with the same area
 * of a world generated by a Java Edition server (Anvil region files, 1.18+ chunk format).
 *
 * Both sides are canonicalised through the Bedrock mapping (Java state -> Bedrock -> Java), so properties Bedrock does
 * not store (fence connections, stair shapes...) never count as differences.
 *
 * Usage:
 *   php tools/compare-vanilla-structure-java.php --data <worldgen data dir> --java-world <world dir> --seed <seed>
 *     (--structure <id or pattern> [--near x,z] | --box minX,minY,minZ,maxX,maxY,maxZ)
 *     [--dimension overworld|nether|end] [--backend compiled|native] [--margin 0] [--samples 5] [--diff-out file]
 *
 * With --structure, the nearest start (like /locate, from --near, default 0,0) gives the box (all pieces, plus
 * --margin blocks). Only chunks the Java world has at status full are compared.
 */

