declare(strict_types=1);

/**
 * Checks and benchmarks the native decoration (native/vanillagen/decor) against the PHP decoration.
 *
 * For every seed, the same areas are generated and populated twice, with decoration=php and decoration=native (the
 * terrain comes from the native core in both), and every block (block and liquid layers), block entity and entity of
 * the populated area must be identical. Areas: a square around the origin and squares at scattered far positions.
 * With --split, chunks are generated by one generator instance and populated by another one, like two worker threads
 * (the populating instance has no recorded terrain heightmaps, which exercises the native callback for them).
 *
 * Usage:
 *   php tools/compare-vanilla-decoration.php --data=<worldgen data dir> --binary=<vanillagen program>
 *       [--seeds=1,2,3] [--size=6] [--far=2] [--dimension=overworld|nether] [--split] [--profile]
 *       [--structures=true|false]
 */

namespace pocketmine\tools\compare_vanilla_decoration;

use pocketmine\nbt\LittleEndianNbtSerializer;
use pocketmine\nbt\TreeRoot;
use pocketmine\utils\Utils;
use pocketmine\world\format\Chunk;
use pocketmine\world\generator\vanilla\native\NativeTerrainClient;
use pocketmine\world\generator\vanilla\native\VanillaNativeBackend;
use pocketmine\world\generator\vanilla\VanillaGenerator;
use pocketmine\world\generator\vanilla\VanillaNetherGenerator;
use pocketmine\world\SimpleChunkManager;
use function array_map;
use function arsort;
use function count;
use function dirname;
use function explode;
use function fwrite;
use function getopt;
use function getrusage;
use function hrtime;
use function is_string;
use function max;
use function min;
use function mt_rand;
use function mt_srand;
use function printf;
use function sys_get_temp_dir;
use const PHP_EOL;
use const STDERR;

require dirname(__DIR__) . '/vendor/autoload.php';

/** @phpstan-var array<string, string|false> $opts */
$opts = getopt("", ["data:", "binary:", "seeds:", "size:", "far:", "dimension:", "split", "profile", "structures:"]);
$data = $opts["data"] ?? null;
$binary = $opts["binary"] ?? null;
if(!is_string($data) || !is_string($binary)){
	fwrite(STDERR, "Usage: php tools/compare-vanilla-decoration.php --data=<dir> --binary=<vanillagen> [--seeds=..] [--size=6] [--far=2] [--split] [--profile]" . PHP_EOL);
	exit(1);
}
$seeds = array_map(fn(string $s) => (int) $s, explode(",", is_string($opts["seeds"] ?? null) ? $opts["seeds"] : "0,12345,-4172144997902289642", 64));
$size = (int) ($opts["size"] ?? 6);
$far = (int) ($opts["far"] ?? 2);
$dimension = is_string($opts["dimension"] ?? null) ? $opts["dimension"] : "overworld";
$split = isset($opts["split"]);
$profile = isset($opts["profile"]);
$structures = is_string($opts["structures"] ?? null) ? $opts["structures"] : "true";

$backend = VanillaNativeBackend::start($binary, sys_get_temp_dir() . "/vanillagen-decoration-compare.log");
$backend->publish();
[$host, $port, $token] = VanillaNativeBackend::endpoint() ?? throw new \RuntimeException("no endpoint");
$stats = new NativeTerrainClient($host, $port, $token, $data, 0);
/** @phpstan-var array<string, array{int, int}> $cpu PHP and vanillagen process CPU time (ns) during population */
$cpu = ["php" => [0, 0], "native" => [0, 0]];

/**
 * CPU time (user + system) of this PHP process, in nanoseconds.
 */
function phpCpu() : int{
	$u = getrusage();
	if($u === false){
		return 0;
	}
	return ($u["ru_utime.tv_sec"] + $u["ru_stime.tv_sec"]) * 1_000_000_000 + ($u["ru_utime.tv_usec"] + $u["ru_stime.tv_usec"]) * 1000;
}

function makeGenerator(string $dimension, int $seed, string $preset) : VanillaGenerator{
	return $dimension === "nether" ? new VanillaNetherGenerator($seed, $preset) : new VanillaGenerator($seed, $preset);
}

/**
 * @phpstan-return array{int, int, int} mismatching blocks, block entities, entities
 */
function compareChunks(Chunk $a, Chunk $b, int $minY, int $maxY) : array{
	$blocks = 0;
	for($s = $minY >> 4; $s < $maxY >> 4; ++$s){
		$sa = $a->getSubChunk($s);
		$sb = $b->getSubChunk($s);
		for($x = 0; $x < 16; ++$x){
			for($z = 0; $z < 16; ++$z){
				for($y = 0; $y < 16; ++$y){
					if($sa->getBlockStateId($x, $y, $z) !== $sb->getBlockStateId($x, $y, $z) || $sa->getLiquidLayerStateId($x, $y, $z) !== $sb->getLiquidLayerStateId($x, $y, $z)){
						++$blocks;
					}
				}
			}
		}
	}
	$serializer = new LittleEndianNbtSerializer();
	$tiles = function(Chunk $c) use ($serializer) : array{
		$out = [];
		foreach($c->getPendingTileNBT() as $nbt){
			$out[] = $serializer->write(new TreeRoot($nbt));
		}
		return $out;
	};
	$entities = function(Chunk $c) use ($serializer) : array{
		$out = [];
		foreach($c->getPendingEntityNBT() as $nbt){
			$out[] = $serializer->write(new TreeRoot($nbt));
		}
		return $out;
	};
	$ta = $tiles($a);
	$tb = $tiles($b);
	$ea = $entities($a);
	$eb = $entities($b);
	return [$blocks, $ta === $tb ? 0 : max(1, count($ta) - count($tb)), $ea === $eb ? 0 : max(1, count($ea) - count($eb))];
}

$failed = false;
$totalPhp = 0;
$totalNative = 0;
$totalChunks = 0;
/** @phpstan-var array<string, int> $profilePhp */
$profilePhp = [];
/** @phpstan-var array<string, int> $profileNative */
$profileNative = [];
foreach($seeds as $seed){
	$basePreset = "data=$data;structures=$structures";
	$sides = [];
	foreach(["php", "native"] as $mode){
		$gen = makeGenerator($dimension, $seed, "$basePreset;decoration=$mode");
		$pop = $split ? makeGenerator($dimension, $seed, "$basePreset;decoration=$mode") : $gen;
		$decorator = $pop->getDecorator();
		if($mode === "native" && $decorator->getNative() === null){
			fwrite(STDERR, "native decoration is not available" . PHP_EOL);
			exit(1);
		}
		if($profile){
			$decorator->profile = [];
		}
		$sides[$mode] = [$gen, $pop];
	}
	$native = $sides["native"][1]->getDecorator()->getNative();
	if($native !== null && $seed === $seeds[0]){
		printf("native features: %d, left to PHP: %d\n", $native->nativeCount(), count($native->unsupported));
		if($profile){
			foreach(Utils::stringifyKeys($native->unsupported) as $id => $reason){
				printf("  PHP: %s (%s)\n", $id, $reason);
			}
		}
	}
	$areas = [[0, 0]];
	mt_srand($seed & 0x7fffffff);
	for($i = 0; $i < $far; ++$i){
		$areas[] = [mt_rand(-20000, 20000), mt_rand(-20000, 20000)];
	}
	$badChunks = 0;
	$badBlocks = 0;
	$badTiles = 0;
	$badEntities = 0;
	$seedChunks = 0;
	$tPhp = 0;
	$tNative = 0;
	foreach($areas as [$ox, $oz]){
		$worlds = [];
		foreach($sides as $mode => [$gen, $pop]){
			$world = new SimpleChunkManager($gen->getDecorator()->level->minY, $gen->getDecorator()->level->minY + $gen->getDecorator()->level->height);
			for($x = -1; $x <= $size; ++$x){
				for($z = -1; $z <= $size; ++$z){
					$world->setChunk($ox + $x, $oz + $z, new Chunk([], false));
					$gen->generateChunk($world, $ox + $x, $oz + $z);
				}
			}
			$cpu0 = phpCpu();
			$go0 = $stats->processCpuTime();
			$t = hrtime(true);
			for($x = 0; $x < $size; ++$x){
				for($z = 0; $z < $size; ++$z){
					$pop->populateChunk($world, $ox + $x, $oz + $z);
				}
			}
			$elapsed = hrtime(true) - $t;
			[$phpTotal, $goTotal] = $cpu[$mode];
			$cpu[$mode] = [$phpTotal + phpCpu() - $cpu0, $goTotal + $stats->processCpuTime() - $go0];
			if($mode === "php"){
				$tPhp += $elapsed;
			}else{
				$tNative += $elapsed;
			}
			$worlds[$mode] = $world;
		}
		$minY = $worlds["php"]->getMinY();
		$maxY = $worlds["php"]->getMaxY();
		for($x = -1; $x <= $size; ++$x){
			for($z = -1; $z <= $size; ++$z){
				$a = $worlds["php"]->getChunk($ox + $x, $oz + $z);
				$b = $worlds["native"]->getChunk($ox + $x, $oz + $z);
				if($a === null || $b === null){
					continue;
				}
				[$blocks, $tiles, $entities] = compareChunks($a, $b, $minY, $maxY);
				if($blocks + $tiles + $entities > 0){
					++$badChunks;
					$badBlocks += $blocks;
					$badTiles += $tiles;
					$badEntities += $entities;
					if($badChunks <= 5){
						printf("  seed %d chunk %d %d: %d blocks, %d tiles, %d entities differ\n", $seed, $ox + $x, $oz + $z, $blocks, $tiles, $entities);
					}
				}
			}
		}
		$seedChunks += $size * $size;
	}
	$totalPhp += $tPhp;
	$totalNative += $tNative;
	$totalChunks += $seedChunks;
	printf("seed %d: %d chunks populated, php %.1f ms/chunk, native %.1f ms/chunk, %s\n", $seed, $seedChunks, $tPhp / 1e6 / $seedChunks, $tNative / 1e6 / $seedChunks,
		$badChunks === 0 ? "identical" : "$badChunks chunks differ ($badBlocks blocks, $badTiles tiles, $badEntities entities)");
	if($badChunks > 0){
		$failed = true;
	}
	if($native !== null){
		$st = $native->stats;
		printf("  native: begin %.2f ms/chunk, place %.2f ms/chunk (PHP applying %.0f writes/chunk: %.2f ms), %.1f batches/chunk\n",
			$st["begin"] / 1e6 / $seedChunks, $st["place"] / 1e6 / $seedChunks, $st["writes"] / $seedChunks, $st["apply"] / 1e6 / $seedChunks, $st["batches"] / $seedChunks);
		foreach(Utils::stringifyKeys($st) as $k => $_){
			$native->stats[$k] = 0;
		}
	}
	if($profile){
		foreach(Utils::stringifyKeys($sides["php"][1]->getDecorator()->profile ?? []) as $id => $ns){
			$profilePhp[$id] = ($profilePhp[$id] ?? 0) + $ns;
		}
		foreach(Utils::stringifyKeys($sides["native"][1]->getDecorator()->profile ?? []) as $id => $ns){
			$profileNative[$id] = ($profileNative[$id] ?? 0) + $ns;
		}
	}
}
printf("total: %d chunks, populate php %.1f ms/chunk, native %.1f ms/chunk (%.0f%%)\n", $totalChunks, $totalPhp / 1e6 / max(1, $totalChunks), $totalNative / 1e6 / max(1, $totalChunks), 100 * $totalNative / max(1, $totalPhp));
foreach(["php", "native"] as $mode){
	printf("  CPU during population (%s): PHP %.1f ms/chunk + vanillagen %.1f ms/chunk = %.1f ms/chunk
", $mode, $cpu[$mode][0] / 1e6 / max(1, $totalChunks), $cpu[$mode][1] / 1e6 / max(1, $totalChunks), ($cpu[$mode][0] + $cpu[$mode][1]) / 1e6 / max(1, $totalChunks));
}
if($profile){
	foreach(["php" => $profilePhp, "native" => $profileNative] as $mode => $prof){
		arsort($prof);
		printf("-- %s: top features (ms/chunk)\n", $mode);
		$i = 0;
		foreach(Utils::stringifyKeys($prof) as $id => $ns){
			printf("   %-50s %7.3f\n", $id, $ns / 1e6 / max(1, $totalChunks));
			if(++$i >= min(25, count($prof))){
				break;
			}
		}
	}
}
$backend->stop();
exit($failed ? 1 : 0);
