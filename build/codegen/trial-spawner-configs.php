declare(strict_types=1);

/**
 * Generates generated/block/trialspawner/TrialSpawnerConfigData.php from the trial spawner configs of a vanilla Java
 * server jar (data/minecraft/trial_spawner/**.json). Bedrock has the same configs (its trial chamber templates name
 * them "minecraft:trial_chamber/<kind>/<mob>/<normal|ominous>" too) but compiles them into the server.
 *
 * Usage: php build/codegen/trial-spawner-configs.php <server.jar>
 */

namespace pocketmine\build\generate_trial_spawner_configs;

use pocketmine\utils\Filesystem;
use pocketmine\utils\Utils;
use function array_is_list;
use function count;
use function dirname;
use function fwrite;
use function is_array;
use function is_dir;
use function json_decode;
use function ksort;
use function mkdir;
use function preg_match;
use function str_repeat;
use function var_export;
use const JSON_THROW_ON_ERROR;
use const PHP_EOL;
use const STDERR;

require dirname(__DIR__, 2) . '/vendor/autoload.php';

if(count($argv) !== 2){
	fwrite(STDERR, "Usage: php " . $argv[0] . " <server.jar>" . PHP_EOL);
	exit(1);
}

$zip = new \ZipArchive();
if($zip->open($argv[1], \ZipArchive::RDONLY) !== true){
	fwrite(STDERR, "Couldn't open " . $argv[1] . PHP_EOL);
	exit(1);
}

/** @var array<string, array<string, mixed>> $configs */
$configs = [];
for($i = 0; $i < $zip->numFiles; ++$i){
	$name = $zip->getNameIndex($i);
	if($name === false || preg_match('~^data/minecraft/trial_spawner/(.+)\.json$~', $name, $matches) !== 1){
		continue;
	}
	$json = $zip->getFromIndex($i);
	if($json === false){
		throw new \RuntimeException("Couldn't read $name");
	}
	$decoded = json_decode($json, true, flags: JSON_THROW_ON_ERROR);
	if(!is_array($decoded)){
		throw new \RuntimeException("$name is not a JSON object");
	}
	$configs["minecraft:" . $matches[1]] = $decoded;
}
$zip->close();
if(count($configs) === 0){
	fwrite(STDERR, "No trial spawner configs found in " . $argv[1] . PHP_EOL);
	exit(1);
}
ksort($configs);

/**
 * var_export() with short arrays and tab indentation.
 */
function export(mixed $value, int $depth) : string{
	if(!is_array($value)){
		return var_export($value, true);
	}
	if(count($value) === 0){
		return "[]";
	}
	$list = array_is_list($value);
	$out = "[\n";
	foreach(Utils::promoteKeys($value) as $key => $item){
		$out .= str_repeat("\t", $depth + 1) . ($list ? "" : var_export($key, true) . " => ") . export($item, $depth + 1) . ",\n";
	}
	return $out . str_repeat("\t", $depth) . "]";
}

$output = Filesystem::fileGetContents(__DIR__ . "/templates/header.php");
$output .= <<<'HEADER'

namespace pocketmine\block\trialspawner;

/**
 * Vanilla trial spawner configs by id (generated by build/codegen/trial-spawner-configs.php from the server jar: do
 * not edit). Each one has the shape of a "normal_config"/"ominous_config" (see {@link TrialSpawnerConfig::fromArray()}).
 * @internal
 */
final class TrialSpawnerConfigData{

	private function __construct(){
		//NOOP
	}

	public const CONFIGS =
HEADER;
$output .= " " . export($configs, 1) . ";\n}\n";

$target = dirname(__DIR__, 2) . "/generated/block/trialspawner/TrialSpawnerConfigData.php";
if(!is_dir(dirname($target))){
	mkdir(dirname($target), 0777, true);
}
Filesystem::safeFilePutContents($target, $output);
echo "Wrote " . count($configs) . " configs to $target\n";
