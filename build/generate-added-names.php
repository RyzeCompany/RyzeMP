//Writes the names this server has and PocketMine-MP 5.44.3 does not, which plugins for 5.44.3 may register themselves:
//  src/item/AddedItemAliases.php        item aliases (StringToItemParser)
//  src/entity/AddedEntitySaveNames.php  entity save names (EntityFactory)
//Usage: php build/generate-added-names.php <path to PocketMine-MP 5.44.3 .phar>

namespace pocketmine\build\generate_added_names;

use pocketmine\entity\EntityFactory;
use pocketmine\item\StringToItemParser;
use function array_keys;
use function count;
use function dirname;
use function escapeshellarg;
use function file_get_contents;
use function file_put_contents;
use function fwrite;
use function is_array;
use function is_string;
use function json_decode;
use function shell_exec;
use function sort;
use function str_replace;
use function strpos;
use function substr;
use function sys_get_temp_dir;
use function tempnam;
use function unlink;
use function var_export;
use const PHP_BINARY;
use const STDERR;

require dirname(__DIR__) . "/vendor/autoload.php";

if(count($argv) !== 2){
	fwrite(STDERR, "Usage: php " . $argv[0] . " <PocketMine-MP 5.44.3 phar>\n");
	exit(1);
}
$phar = str_replace("\\", "/", $argv[1]);

/**
 * Runs the PHP code (after loading the 5.44.3 autoloader) in a new process and returns the strings it prints as JSON.
 * @return true[]
 * @phpstan-return array<string, true>
 */
function upstreamNames(string $phar, string $code) : array{
	$script = tempnam(sys_get_temp_dir(), "names");
	if($script === false){
		throw new \RuntimeException("Could not create a temporary file");
	}
	file_put_contents($script, '<?php require "phar://' . $phar . '/vendor/autoload.php"; ' . $code);
	$names = json_decode((string) shell_exec(escapeshellarg(PHP_BINARY) . " " . escapeshellarg($script)), true);
	@unlink($script);
	if(!is_array($names)){
		throw new \RuntimeException("Could not read the names of $phar");
	}
	$known = [];
	foreach($names as $name){
		if(is_string($name)){
			$known[$name] = true;
		}
	}
	return $known;
}

/**
 * @param string[]|int[] $ours     names (PHP turns numeric string keys into ints)
 * @param true[]         $upstream
 * @phpstan-param array<int|string> $ours
 * @phpstan-param array<string, true> $upstream
 * @return string[]
 * @phpstan-return list<string>
 */
function added(array $ours, array $upstream) : array{
	$added = [];
	foreach($ours as $name){
		$name = (string) $name;
		if(!isset($upstream[$name])){
			$added[] = $name;
		}
	}
	sort($added);
	return $added;
}

/**
 * @param string[] $names
 * @phpstan-param list<string> $names
 */
function writeList(string $file, string $namespace, string $class, string $doc, array $names) : void{
	$list = "";
	foreach($names as $name){
		$list .= "\t\t" . var_export($name, true) . ",\n";
	}
	//the licence header of this file
	$self = (string) file_get_contents(__FILE__);
	$start = (int) strpos($self, "/*");
	$license = substr($self, $start, (int) strpos($self, "*/") + 2 - $start);
	file_put_contents($file, <<<PHP
<?php

$license

declare(strict_types=1);

namespace $namespace;

/**
$doc
 *
 * This file is generated by build/generate-added-names.php. Do not edit it by hand.
 * @internal
 */
final class $class{
	public const LIST = [
$list	];
}

PHP);
	echo "Wrote " . count($names) . " names to $file\n";
}

$items = added(
	StringToItemParser::getInstance()->getKnownAliases(),
	upstreamNames($phar, 'echo json_encode(pocketmine\item\StringToItemParser::getInstance()->getKnownAliases());')
);
writeList(dirname(__DIR__) . "/src/item/AddedItemAliases.php", "pocketmine\\item", "AddedItemAliases",
	" * Item aliases this server has and PocketMine-MP 5.44.3 does not. Plugins for 5.44.3 may register them themselves:\n" .
	" * StringToItemParser keeps ours and lets those plugins load (see StringToTParser::keepBuiltIn()).",
	$items
);

$creationFuncs = new \ReflectionProperty(EntityFactory::class, "creationFuncs");
/** @var array<string, mixed> $ourEntities */
$ourEntities = $creationFuncs->getValue(EntityFactory::getInstance());
$entities = added(
	array_keys($ourEntities),
	upstreamNames($phar, '$f = pocketmine\entity\EntityFactory::getInstance(); echo json_encode(array_keys((new ReflectionProperty($f, "creationFuncs"))->getValue($f)));')
);
writeList(dirname(__DIR__) . "/src/entity/AddedEntitySaveNames.php", "pocketmine\\entity", "AddedEntitySaveNames",
	" * Entity save names this server has and PocketMine-MP 5.44.3 does not. Plugins for 5.44.3 may register entities\n" .
	" * under them (e.g. their own \"Creeper\"): EntityFactory keeps ours for loading saved entities and lets those plugins\n" .
	" * load.",
	$entities
);
